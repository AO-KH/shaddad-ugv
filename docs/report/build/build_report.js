// ---------------------------------------------------------------- chapters -> paragraphs
let listInstance = 0;
function chapterContent(ch) {
  const out = [];
  const s = secInfo[ch.id];
  const bmId = 'sec_' + ch.id.replace(/[^A-Za-z0-9_]/g, '_');
  const h1Text = s.front ? ch.title : `${s.num}. ${ch.title}`;
  out.push(new Paragraph({
    heading: HeadingLevel.HEADING_1, pageBreakBefore: true,
    children: [new Bookmark({ id: bmId, children: [new TextRun(h1Text)] })],
  }));
  let h2 = 0, h3 = 0, pendingBreak = false;
  const blocks = ch.blocks;
  blocks.forEach((b, i) => {
    const next = blocks[i + 1];
    const brk = pendingBreak; pendingBreak = false;
    switch (b.type) {
      case 'h2': {
        h2 += 1; h3 = 0;
        let t = stripMarkup(b.text);
        if (TITLECASE_CHAPTERS.has(ch.id)) t = sentenceCase(t);
        out.push(new Paragraph({ heading: HeadingLevel.HEADING_2, pageBreakBefore: brk, children: [new Bookmark({ id: b._anchor, children: [new TextRun(s.front ? t : `${s.num}.${h2} ${t}`)] })] }));
        break;
      }
      case 'h3': {
        h3 += 1;
        let t = stripMarkup(b.text);
        if (TITLECASE_CHAPTERS.has(ch.id)) t = sentenceCase(t);
        out.push(new Paragraph({ heading: HeadingLevel.HEADING_3, pageBreakBefore: brk, children: [new Bookmark({ id: b._anchor, children: [new TextRun(s.front ? t : `${s.num}.${h2}.${h3} ${t}`)] })] }));
        break;
      }
      case 'p': {
        // a paragraph directly before a table or code block always stays with it (the table caption, header and first
        // rows, or the short code block, keep together); before a list or figure only when it ends with a colon
        const leadIn = next && (['code', 'table'].includes(next.type)
          || (/:\s*$/.test(b.text) && ['bullets', 'numbered', 'figure'].includes(next.type)));
        out.push(new Paragraph({ pageBreakBefore: brk, keepNext: leadIn || !!b.keepNext, children: inl(b.text, {}, ch.id) }));
        break;
      }
      case 'bullets':
      case 'numbered': {
        const ref = b.type === 'bullets' ? 'nasl-bullets' : 'nasl-numbers';
        if (!(b.continue && b.type === 'numbered')) listInstance += 1;
        b.items.forEach((it, k) => {
          const last = k === b.items.length - 1;
          // the first item keeps with the second (a heading never strands with one item at a page bottom);
          // a last item that introduces a code block or table keeps with it
          const keepNext = (k === 0 && b.items.length >= 2)
            || (last && /:\s*$/.test(it) && next && ['code', 'table'].includes(next.type));
          out.push(new Paragraph({
            numbering: { reference: ref, level: 0, instance: listInstance },
            spacing: { before: 0, after: last ? 140 : 70 }, keepNext,
            children: inl(it, {}, ch.id),
          }));
        });
        break;
      }
      case 'table': if (brk) out.push(new Paragraph({ pageBreakBefore: true, children: [] })); out.push(...dataTable(b, ch.id)); break;
      case 'figure': if (brk) out.push(new Paragraph({ pageBreakBefore: true, children: [] })); out.push(...figureBlock(b, ch.id)); break;
      case 'code': if (brk) out.push(new Paragraph({ pageBreakBefore: true, children: [] })); out.push(...codeBlock(b)); break;
      case 'note': if (brk) out.push(new Paragraph({ pageBreakBefore: true, children: [] })); out.push(...noteBlock(b, ch.id)); break;
      case 'pagebreak': pendingBreak = !IGNORE_PAGEBREAKS.has(ch.id); break;
      default: warn(`unknown block type ${b.type} in ${ch.id}`);
    }
  });
  return out;
}

