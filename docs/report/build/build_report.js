function pctToDxa(widths, total = TEXT_W) {
  const sum = widths.reduce((a, b) => a + b, 0);
  const out = widths.map((w) => Math.floor((w / sum) * total));
  out[out.length - 1] += total - out.reduce((a, b) => a + b, 0);
  return out;
}

