async function main() {
  let buf = await Packer.toBuffer(doc);
  // keep full image resolution (dense Simulink diagrams) - Word must not down-sample on save/PDF export
  const JSZip = require('jszip');
  const zip = await JSZip.loadAsync(buf);
  let settings = await zip.file('word/settings.xml').async('string');
  if (!settings.includes('doNotAutoCompressPictures')) {
    if (/<w:decimalSymbol/.test(settings)) settings = settings.replace(/<w:decimalSymbol/, '<w:doNotAutoCompressPictures/><w:decimalSymbol');
    else settings = settings.replace('</w:settings>', '<w:doNotAutoCompressPictures/></w:settings>');
    zip.file('word/settings.xml', settings);
  }
  buf = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
  fs.writeFileSync(OUT_DOCX, buf);
  console.log(`docx written: ${OUT_DOCX} (${(buf.length / 1e6).toFixed(1)} MB)`);
  console.log(`chapters: ${chapters.length} (missing: ${missing.length ? missing.join(', ') : 'none'}), figures: ${figN}, tables: ${tabN}`);
  if (process.argv.includes('--no-pdf')) return;
  const ps1 = path.join(BUILD_DIR, 'convert_to_pdf.ps1');
  const r = cp.spawnSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', ps1, '-Docx', OUT_DOCX, '-Pdf', OUT_PDF], { stdio: 'inherit' });
  if (r.status !== 0) { console.error('PDF conversion failed'); process.exitCode = 1; return; }
  // Word's PDF export down-samples pictures to about 200 ppi; put the original figure files back
  // so the dense Simulink diagrams stay legible when zoomed (layout is untouched).
  const orderFile = path.join(BUILD_DIR, 'figure_order.json');
  fs.writeFileSync(orderFile, JSON.stringify(figureOrder, null, 1));
  const py = cp.spawnSync('python', ['-I', path.join(BUILD_DIR, 'pdf_fullres_images.py'), OUT_PDF, orderFile, FIG_DIR], { stdio: 'inherit' });
  if (py.status !== 0) console.warn('full-resolution image step failed - PDF keeps the down-sampled images from Word');
  if (warnings.length) console.log(`${warnings.length} warning(s)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
