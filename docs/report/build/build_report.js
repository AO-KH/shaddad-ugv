function codeBlock(b) {
  const lines = String(b.text).replace(/\t/g, '    ').replace(/\s+$/, '').split('\n');
  const maxLen = Math.max(...lines.map((l) => l.length), 1);
  const avail = (TEXT_W - 160 - 100 - 80) / 20; // pt available for text
  let size = Math.floor((avail / (0.5498 * maxLen)) * 0.98 * 2); // half-points
  size = Math.max(14, Math.min(18, size)); // 7 .. 9 pt
  const charDxa = 0.5498 * (size / 2) * 20;
  const fitChars = Math.floor((avail * 20) / charDxa);
  // blocks of more than 15 lines may break across a page (first and last three lines stay together), so a long
  // listing does not push its heading and lead-in to the next page and leave a gap (fix round 2)
  const longCode = lines.length > 15;
  const paras = lines.map((l, li) => {
    let indent;
    if (l.length > fitChars) { // wrapped line: continuation aligned under the comment (or 4 chars in)
      const c = l.search(/\s%/);
      const lead = l.match(/^\s*/)[0].length;
      const col = c > 0 && c < fitChars - 10 ? c + 1 : lead + 4;
      indent = { left: Math.round(col * charDxa), hanging: Math.round(col * charDxa) };
    }
    return new Paragraph({
      // short blocks stay on one page; the last line does not chain the block to what follows
      spacing: { before: 0, after: 0, line: 240 }, keepLines: true, indent,
      keepNext: li < lines.length - 1 && (lines.length <= 12 || (longCode && (li < 2 || li >= lines.length - 3))),
      children: [new TextRun({ text: l.length ? l : ' ', font: MONO, size, color: '23232B' })],
    });
  });
  return [
    new Table({
      width: { size: TEXT_W, type: WidthType.DXA }, columnWidths: [TEXT_W], layout: TableLayoutType.FIXED,
      borders: noBorders,
      rows: [new TableRow({
        cantSplit: !longCode,
        children: [new TableCell({
          width: { size: TEXT_W, type: WidthType.DXA },
          margins: { top: 90, bottom: 90, left: 160, right: 100 },
          shading: { type: ShadingType.CLEAR, color: 'auto', fill: C.codeFill },
          borders: { top: none, bottom: none, right: none, left: { style: BorderStyle.SINGLE, size: 18, color: C.purple } },
          children: paras,
        })],
      })],
    }),
    spacer(12),
  ];
}

