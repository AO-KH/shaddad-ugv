function resolveFig(file, chId) {
  if (figNumByChapter[chId] && figNumByChapter[chId][file]) return figNumByChapter[chId][file];
  const cur = secInfo[chId] ? secInfo[chId].idx : 0;
  const before = figOccur.filter((o) => o.file === file && o.chIdx < cur);
  if (before.length) return before[before.length - 1].num;
  const any = figOccur.find((o) => o.file === file);
  return any ? any.num : null;
}

function resolveRef(kind, key, chId) {
  if (kind === 'fig') {
    const n = resolveFig(key, chId);
    if (!n) { warn(`unresolved {fig:${key}} in ${chId}`); return { text: '[figure not found]', anchor: null }; }
    return { text: 'Figure ' + n, anchor: 'fig_' + n };
  }
  if (kind === 'tab') {
    let n = tabByChapter[chId] && tabByChapter[chId][key];
    if (!n) {
      const cur = secInfo[chId] ? secInfo[chId].idx : 0;
      const before = tabOccur.filter((o) => o.id === key && o.chIdx < cur);
      n = before.length ? before[before.length - 1].num : tabById[key];
    }
    if (!n) { warn(`unresolved {tab:${key}} in ${chId}`); return { text: '[table not found]', anchor: null }; }
    return { text: 'Table ' + n, anchor: 'tab_' + n };
  }
  if (kind === 'sec' && key.includes('/')) {
    const cut = key.indexOf('/');
    const chKey = key.slice(0, cut).trim();
    const h = headNum[chKey] && headNum[chKey][normHead(key.slice(cut + 1))];
    if (!h) { warn(`unresolved {sec:${key}} in ${chId}`); return { text: '[section not found]', anchor: null }; }
    return { text: h.num ? 'Section ' + h.num : h.title, anchor: h.anchor };
  }
  if (kind === 'sec') {
    const s = secInfo[key];
    if (!s) { warn(`unresolved {sec:${key}} in ${chId}`); return { text: '[section not found]', anchor: null }; }
    return { text: s.front ? s.title : 'Section ' + s.num, anchor: 'sec_' + key.replace(/[^A-Za-z0-9_]/g, '_') };
  }
  return { text: `{${kind}:${key}}`, anchor: null };
}

// ---------------------------------------------------------------- inline markup
const RE_TOKEN = /(`[^`]+`)|(\*\*(?=\S)[\s\S]+?(?<=\S)\*\*)|((?<![\w*])\*(?=[^\s*])[^*]+?(?<=\S)\*(?![\w*]))|(\{(fig|tab|sec):([^}]+)\})/;

function plainRuns(text, st) {
  // highlight [TBD ...] markers in brand magenta
  const out = [];
  // table cells: long unbroken names (block paths such as Power_Plant/Battery_Pack) may break after / or _
  if (st.codeBreaks) text = text.replace(/\S{15,}/g, (w) => w.replace(/([_/])(?=[A-Za-z0-9]{3})/g, '$1​'));
  const parts = text.split(/(\[TBD[^\]]*\])/);
  for (const p of parts) {
    if (!p) continue;
    const tbd = /^\[TBD/.test(p);
    out.push(new TextRun({
      text: p, bold: st.bold || tbd, italics: st.italics, size: st.size, font: st.font,
      color: tbd ? C.magenta : st.color,
    }));
  }
  return out;
}

function inl(text, st, chId) {
  st = Object.assign({ size: BODY_SIZE, color: undefined, bold: false, italics: false }, st || {});
  const out = [];
  let rest = String(text == null ? '' : text);
  while (rest.length) {
    const m = rest.match(RE_TOKEN);
    if (!m) { out.push(...plainRuns(rest, st)); break; }
    if (m.index > 0) out.push(...plainRuns(rest.slice(0, m.index), st));
    if (m[1]) {
      let code = m[1].slice(1, -1);
      // in narrow table cells: allow line breaks (zero-width space) only after _ / \ when at least 3 characters
      // follow, after . when a name part of 5+ characters follows (never before .m / .slx), and after ( { ,
      if (st.codeBreaks && code.length > 12) {
        code = code.replace(/([_/\\])(?=[A-Za-z0-9]{3})/g, '$1​').replace(/\.(?=[A-Za-z_][A-Za-z0-9_]{4})/g, '.​')
          .replace(/([({,])(?=\S)/g, '$1​');
      }
      out.push(new TextRun({
        text: code, font: MONO, size: st.codeSize || st.size - 1, bold: st.bold, italics: st.italics,
        color: st.codeColor || C.codeText,
      }));
    } else if (m[2]) {
      out.push(...inl(m[2].slice(2, -2), Object.assign({}, st, { bold: true }), chId));
    } else if (m[3]) {
      out.push(...inl(m[3].slice(1, -1), Object.assign({}, st, { italics: true }), chId));
    } else if (m[4]) {
      const r = resolveRef(m[5], m[6].trim(), chId);
      const run = new TextRun({ text: r.text, bold: st.bold, italics: st.italics, size: st.size, color: st.linkColor || C.purple });
      out.push(r.anchor ? new InternalHyperlink({ anchor: r.anchor, children: [run] }) : run);
    }
    rest = rest.slice(m.index + m[0].length);
  }
  return out;
}

const stripMarkup = (s) => String(s).replace(/\*\*/g, '').replace(/`/g, '').replace(/(?<![\w*])\*(?=\S)([^*]+?)\*(?![\w*])/g, '$1');

function sentenceCase(s) {
  const words = s.split(' ');
  const STOP = new Set(['with', 'from', 'into', 'over', 'than', 'that', 'this', 'onto', 'upon', 'when', 'what', 'where', 'without']);
  const content = words.slice(1).map((w) => w.replace(/^[^A-Za-z]+|[^A-Za-z]+$/g, '')).filter((w) => /^[A-Za-z]{4,}$/.test(w) && !STOP.has(w));
  if (!content.length || !content.every((w) => /^[A-Z]/.test(w))) return s; // not Title Case
  const low = (p) => {
    const m = p.match(/^([^A-Za-z]*)([A-Z][a-z]+)([^A-Za-z]*)$/);
    if (!m || KEEP_CAPS.has(m[2])) return p;
    return m[1] + m[2].toLowerCase() + m[3];
  };
  return words.map((w, i) => w.split('-').map((p, j) => (i === 0 && j === 0 ? p : low(p))).join('-')).join(' ');
}

// ---------------------------------------------------------------- image helpers
function imageSize(file) {
  const b = fs.readFileSync(file);
  if (b[0] === 0x89 && b[1] === 0x50) return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), type: 'png', data: b };
  if (b[0] === 0xff && b[1] === 0xd8) {
    let i = 2;
    while (i < b.length) {
      if (b[i] !== 0xff) { i++; continue; }
      const marker = b[i + 1];
      const len = b.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7), type: 'jpg', data: b };
      }
      i += 2 + len;
    }
  }
  throw new Error('unsupported image ' + file);
}

function figureRun(file, widthCm) {
  const full = path.join(FIG_DIR, file);
  if (!fs.existsSync(full)) { warn('figure file missing ' + file); return null; }
  const im = imageSize(full);
  let w = widthCm ? Math.round(widthCm * PX_PER_CM) : MAX_FIG_W_PX;
  w = Math.min(w, MAX_FIG_W_PX);
  let h = Math.round((w * im.h) / im.w);
  const maxH = OVERVIEW_H_CM[file] ? Math.round(OVERVIEW_H_CM[file] * PX_PER_CM)
    : /_overview\.png$/.test(file) ? OVERVIEW_MAX_H_PX : MAX_FIG_H_PX;
  if (h > maxH) { h = maxH; w = Math.round((h * im.w) / im.h); }
  return new ImageRun({ type: im.type, data: im.data, transformation: { width: w, height: h }, altText: { title: file, description: file, name: file } });
}

