function [F, S, B, T] = pp_log_cols()
%PP_LOG_COLS  Column indices of the To Workspace logs of tb_power_plant / tb_shift_cycle (owner: power, T05).
%   [F, S, B, T] = pp_log_cols()   F.<name> = column of log_fast (Ts.base), S.<name> = log_slow (Ts.ctrl),
%   B.<name> = log_bms (BMS telemetry, 0.1 s), T.<name> = log_truth (Bus_PowerTruth summary, 0.1 s).
%   Must match scripts/build/build_tb_power_plant.m (local_bench, '*_mux' blocks).
f = {'t', 'V_pack', 'I_pack', 'V_bus', 'V_24', 'I_24', 'V_24IMP', 'V_12', 'I_12', 'V_5', 'V_3V3', ...
     'Rail24_ok', 'Rail12_ok', 'Rail5_ok', 'Rail3V3_ok', 'K1', 'K2', 'K3', 'K4', ...
     'Safety_OK', 'Safety_HV_OK', 'EStop_Any', 'Ch1_OK', 'Ch2_OK', 'Latched_off', 'Dock', 'Key_On', 'Fuse_Blown', ...
     'I_loadL', 'I_loadR', 'w_impl', 'T_load', 'V_drvL', 'V_drvR'};
s = {'t', 'Impl_Running', 'Impl_Fault', 'Impl_Ready', 'Impl_Speed', 'Impl_Torque', 'Impl_Power', 'Impl_Current', ...
     'Impl_Fault_Code', 'K1_Cmd', 'K2_Cmd', 'K4_Cmd', 'Charger_Enable', 'I_req', 'Fan_Cmd', 'HV_req', 'Impl_en_cmd', ...
     'Impl_spd_cmd'};
b = {'t', 'Contactor_State', 'HV_Ready', 'Fault_Level', 'Fault_Word', 'Warning_Word', 'SOC_pack', 'Charging_Active', ...
     'Charge_Complete', 'I_chg_lim_A', 'I_dis_lim_A', 'T_cell_max_K', 'Fan_Cmd', 'K1_Closed', 'Runtime_Remaining_s'};
t = {'t', 'SOC_pack_true', 'T_cell_max_K', 'T_cell_min_K', 'V_term_V', 'I_pack_A', 'E_out_Wh', 'E_in_Wh', 'E_chg_bus_Wh', ...
     'E_trac_dc_Wh', 'E_impl_dc_Wh', 'E_lv_Wh', 'E_dcdc_loss_Wh', 'E_pdu_loss_Wh', 'E_loss_batt_Wh', 'I_pack_peak_A', ...
     'P_grid_W', 'SOC_true_min', 'V_cell_true_max'};
F = cell2struct(num2cell(1:numel(f)), f, 2);
S = cell2struct(num2cell(1:numel(s)), s, 2);
B = cell2struct(num2cell(1:numel(b)), b, 2);
T = cell2struct(num2cell(1:numel(t)), t, 2);
end
