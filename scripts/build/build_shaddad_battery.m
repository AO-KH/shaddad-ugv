function info = build_shaddad_battery()
%BUILD_SHADDAD_BATTERY  Simscape Battery Builder -> generated pack libraries (owner: power, T04).
%
%   info = build_shaddad_battery()
%
%   Generates (docs/specs/power.md section 2.2, 3.1 B1-B3 and Appendix A; build plan T04.1):
%     subsystems/power/Shaddad_Battery_lib.slx         block Shaddad_Pack (Ns parallel-assembly
%                                                       models, Ns x Np Grouped, passive balancing,
%                                                       cell-based ambient thermal path, PercentDeviation)
%     subsystems/power/Shaddad_Battery_param.m         generated parameter script (reference only)
%     subsystems/power/Shaddad_Battery_Lumped_lib.slx  block Shaddad_Pack_Lumped (1 model)
%     subsystems/power/Shaddad_Battery_Lumped_param.m
%   The generated blocks use mask parameter variable names (MaskParameters 'VariableNamesByType');
%   the Pack_Grouped / Pack_Lumped SSRs (build_power_pack) overwrite every mask value with a
%   P.power.* expression, so the generated *_param.m scripts are never run by the models.
%
%   info : struct with the generated block paths, mask parameter names, port summary and the
%          probe variables of the first parallel assembly (used by build_power_pack).
%
%   Idempotent: closes / deletes the previous libraries first. Library files are generated by
%   buildBattery (do not hand-edit). Needs no base-workspace variables (reads param_power()).

Pw = param_power();
c0 = Pw.cell;
pk = Pw.pack;
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outDir = fullfile(root, 'subsystems', 'power');

libs = {'Shaddad_Battery_lib', 'Shaddad_Battery_Lumped_lib'};
for k = 1:numel(libs)
    if bdIsLoaded(libs{k}), close_system(libs{k}, 0); end
    f = fullfile(outDir, [libs{k} '.slx']);
    if isfile(f), delete(f); end
end
for f = {'Shaddad_Battery_param.m', 'Shaddad_Battery_Lumped_param.m', 'Shaddad_Battery.mat', 'Shaddad_Battery_Lumped.mat'}
    ff = fullfile(outDir, f{1});
    if isfile(ff), delete(ff); end
end
% generated Simscape packages (buildBattery refuses to overwrite an existing package folder)
for d = {'+Shaddad_Battery', '+Shaddad_BatteryLumpingAdapters', '+Shaddad_Battery_Lumped', ...
         '+Shaddad_Battery_LumpedLumpingAdapters'}
    dd = fullfile(outDir, d{1});
    if isfolder(dd), rmdir(dd, 's'); end
end

%% ---- cell (B1): batt_lib/Cells/Battery Equivalent Circuit, 1 RC, lumped thermal mass ----
g = batteryCylindricalGeometry();           % 21700 (Molicel P42A)
g.Radius = simscape.Value(c0.D/2, 'm');
g.Height = simscape.Value(c0.H, 'm');
c = batteryCell(g);
c.Mass = simscape.Value(c0.mass, 'kg');
c.Capacity = simscape.Value(c0.Q_Ah, 'A*hr');
c.Energy = simscape.Value(c0.Q_Ah*c0.V_nom, 'W*hr');
bp = c.CellModelOptions.BlockParameters;
bp.ThermalModel          = "LumpedThermalMass";
bp.RCPairs               = "rc1";
bp.CurrentDependence     = "Disabled";
bp.HysteresisModel       = "none";
bp.SelfDischargeResistor = "Disabled";
bp.CyclingAgingMethod    = "disabled";
c.CellModelOptions.BlockParameters = bp;

%% ---- parallel assembly Np and module Ns (B2, Grouped: Ns models) ----
pa = batteryParallelAssembly(c, pk.Np);
m = batteryModule(pa, pk.Ns);
m.ModelResolution        = "Grouped";
m.SeriesGrouping         = ones(1, pk.Ns);
m.ParallelGrouping       = ones(1, pk.Ns);
m.BalancingStrategy      = "Passive";
m.AmbientThermalPath     = "CellBasedThermalResistance";
m.CoolantThermalPath     = "None";
m.CellParameterVariation = "PercentDeviation";
m.NonCellResistance      = "on";
m.InterCellThermalPath   = "off";
m.MassFactor             = pk.MassFactor;
m.Name                   = "Shaddad_Pack";

%% ---- fast lumped module (B3) ----
paL = batteryParallelAssembly(c, pk.Np);
mL = batteryModule(paL, pk.Ns);
mL.ModelResolution        = "Lumped";
mL.BalancingStrategy      = "None";
mL.AmbientThermalPath     = "CellBasedThermalResistance";
mL.CoolantThermalPath     = "None";
mL.CellParameterVariation = "NoVariation";
mL.NonCellResistance      = "on";
mL.MassFactor             = pk.MassFactor;
mL.Name                   = "Shaddad_Pack_Lumped";

buildBattery(m,  LibraryName = "Shaddad_Battery", Directory = outDir, ...
    MaskParameters = "VariableNamesByType");
buildBattery(mL, LibraryName = "Shaddad_Battery_Lumped", Directory = outDir, ...
    MaskParameters = "VariableNamesByType");

%% ---- report the generated interface ----
info = struct('module', m, 'moduleLumped', mL, 'NumModels', m.NumModels, ...
    'CumulativeMass_kg', value(m.CumulativeMass, 'kg'), 'blocks', {{}}, 'masks', {{}});
for k = 1:numel(libs)
    load_system(fullfile(outDir, [libs{k} '.slx']));
    blk = find_system(libs{k}, 'SearchDepth', 1, 'Type', 'block');
    blk = blk(~strcmp(blk, libs{k}));
    info.blocks{k} = blk;
    if ~isempty(blk)
        info.masks{k} = get_param(blk{1}, 'MaskNames');
    end
end
end
