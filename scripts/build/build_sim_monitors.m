Ln(s, 'T_start/1', 'T_since/2', 't_start');
Ln(s, 'T_since/1', 'T_mission/1', '');
Ln(s, 'Seen_auto/1', 'T_mission/2', 'seen_auto');
Ln(s, 'Zero_t/1', 'T_mission/3', '');

%% ---- NaN / Inf guard ----
A(s, 'simulink/Signal Routing/Vector Concatenate', 'Guard_vec', 'NumInputs', '9');
A(s, 'simulink/Logic and Bit Operations/Relational Operator', 'Is_finite', 'Operator', 'isFinite');
A(s, 'simulink/Logic and Bit Operations/Logical Operator', 'Not_finite', 'Operator', 'NOT');
