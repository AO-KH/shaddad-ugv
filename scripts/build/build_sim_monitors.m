    'StopWhenAssertionFail', 'on', 'SampleTime', 'Ts.monitor');
% the nine guarded signals, in the order of Guard_vec: truth (4), power_truth (3), drive_truth (2)
SEL('Sel_truth_guard', 'RT_truth/1', {'pos_W', 'vel_W', 'eul', 'omega_B'}, ...
    {'Guard_vec/1', 'Guard_vec/2', 'Guard_vec/3', 'Guard_vec/4'}, 'truth_10Hz');
