% -------------------------------------------------------------------------------------------
function local_foreach(s, name, nCol, kind)
% For Each Subsystem: input 1 = obstacle table (partitioned along rows), 2 = footprint centre p (2x1),
% 3 = footprint rotation R (2x2, body -> world); output = separation per row (concatenated along dim 1).
% Inside, one MATLAB Function Sep (D70) calls mon_sep_circle or mon_sep_rect (subsystems/integration) in one
% line; they do what the former block networks did, in the same order (bit-identical, t_mf_equiv). The
% footprint half extents hA reach its 4th input from a Constant block, not as parameter data: MATLAB Function
% parameter data trips the R2026b Stateflow JIT relink assertion 'o != nullptr' inside Subsystem References
% (see build_rc_link, build_drive). With the function called as an external file, the first compile after a
% load still hit that assertion (tb_sim_monitors, t_framework/testMonitorSepDist, 2026-11-14), so the block
% holds a verbatim copy of the file as a local function of the same name, as build_structure (MFB) does: the
% file stays the single source; rebuild after editing it (t_mf_equiv/testMonitorsUseFunctions checks the copies).
switch kind
    case 'circle'
        fcn = 'mon_sep_circle';
    case 'rect'
        fcn = 'mon_sep_rect';
    otherwise
        error('build_sim_monitors:kind', 'kind');
end
fe = [s '/' name];
add_block('simulink/Ports & Subsystems/For Each Subsystem', fe);
delete_line(fe, 'In1/1', 'Out1/1');
set_param([fe '/In1'], 'Name', 'row');
set_param([fe '/Out1'], 'Name', 'sep');
% each iteration's separation leaves as a 1 x 1 matrix, as it did from the former blocks, so the For Each output
% stays a K x 1 matrix: the scalar output of the MATLAB Function alone makes it a 1-D vector (measured, R2026b),
% and the logged minima mon_sep_* would change from 1 x 1 to scalar
set_param([fe '/sep'], 'PortDimensions', '[1 1]');
add_block('simulink/Sources/In1', [fe '/p'], 'Port', '2');
add_block('simulink/Sources/In1', [fe '/R'], 'Port', '3');
feb = find_system(fe, 'SearchDepth', 1, 'BlockType', 'ForEach');
set_param(feb{1}, 'InputPartition', {'on', 'off', 'off'}, 'InputPartitionDimension', {'1', '1', '1'}, ...
    'InputPartitionWidth', {'1', '1', '1'}, 'OutputConcatenationDimension', {'1'});
add_block('simulink/Sources/Constant', [fe '/hA'], 'Value', 'P.sim.mon.footprint(:)/2', 'SampleTime', '-1');
mf = [fe '/Sep'];
add_block('simulink/User-Defined Functions/MATLAB Function', mf);
cfg = get_param(mf, 'MATLABFunctionConfiguration');
body = fileread(fullfile(char(currentProject().RootFolder), 'subsystems', 'integration', [fcn '.m']));
cfg.FunctionScript = [sprintf('function sep = fcn(row, p, R, hA)\n%%#codegen\nsep = %s(row, p, R, hA);\nend\n\n', fcn), ...
    sprintf(['%% ---- verbatim copy of subsystems/integration/%s.m (generated by build_sim_monitors, do not ' ...
    'edit here) ----\n'], fcn), strrep(body, sprintf('\r\n'), newline)];
cfg.UpdateMethod = 'Inherited';
cfg.SaturateOnIntegerOverflow = false;
cfg.Description = sprintf('Separation footprint <-> obstacle row (%s): subsystems/integration/%s.m (D70)', kind, fcn);
Ln = @(src, dst, nm) shaddad_bu('nline', fe, src, dst, nm);
Ln('row/1', 'Sep/1', 'row');
Ln('p/1', 'Sep/2', 'p');
Ln('R/1', 'Sep/3', 'R');
Ln('hA/1', 'Sep/4', 'hA');
Ln('Sep/1', 'sep/1', 'sep');
set_param(fe, 'Description', sprintf(['Planar separation footprint <-> obstacle (%s), one iteration per ' ...
    'table row (%d columns): MATLAB Function Sep -> %s (D70).'], kind, nCol, fcn));
end

