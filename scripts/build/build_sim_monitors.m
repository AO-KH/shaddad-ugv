function build_sim_monitors()
%BUILD_SIM_MONITORS  Generate subsystems/integration/Sim_Monitors.slx (Subsystem Reference, build plan T16.1).
%
%   Ports (ICD 3.1): 1 truth (Bus_TruthState, 1 ms), 2 power_truth (0.1), 3 drive_truth (1 ms),
%   4 obs (Bus_ObstaclesDyn, 0.01), 5 telem (0.01), 6 gnc_status (0.2), 7 struct_diag (0.01)
%   -> 1 kpi (Bus_SimKPI, 0.1).
%
%   Contents (integration spec 4.5, D22/D40/D42), library blocks except the two MATLAB Functions of D70:
%   * Footprint pose: navlib 'Coordinate Transformation Conversion' (Euler ZYX [psi 0 0] + translation
%     -> homogeneous transform), footprint P.sim.mon.footprint (1.4 x 1.1 m).
%   * Three 'For Each Subsystem's: K_c = 12 nearest static cylinders (P.world.obstacles.cyl, nearest
%     selection with dspstat3/Sort + Selector), K_b = 8 nearest static boxes incl. yaw and the greenhouse
%     film segments converted at initialisation to 0.02 m thick boxes (utilities/sim_monitor_obstacles.m),
%     4 dynamic cylinders from ScenarioIn.obs (rows > n ignored).
%     Separation per obstacle = exact planar distance between the oriented footprint rectangle and the
%     obstacle (circle: clamped point-rectangle distance; box: vertex-rectangle distances both ways plus a
%     separating-axis overlap test giving the negative penetration), one MATLAB Function Sep in each For
%     Each (D70): subsystems/integration/mon_sep_circle.m and mon_sep_rect.m (copied into the blocks, see
%     local_foreach) do what the former element-wise block networks did, operation for operation (bit-identical,
%     tests/integration/t_mf_equiv). DEVIATION
%     from the plan text: robotslcollision 'Check Collision' / 'Collision Box' / 'Collision Cylinder' need a
%     C compiler for SimulateUsing 'Code generation' (none installed) and, in 'Interpreted execution', return
%     the last iteration's result for every iteration of a For Each Subsystem (measured: 12 identical
%     SepDist values) at about 1.5 ms per call. They are used as the reference oracle in
%     tests/integration/t_framework (T-INT-12) instead.
%   * clear_min / collision / n_coll over all obstacles; per-class minima logged (mon_sep_cyl,
%     mon_sep_box, mon_sep_dyn).
%   * Energy audit from the plant integrals (D40): E_batt, E_regen, eps_el, eps_mech (E_mech0 latched at
%     the first sample), I_batt_peak = power_truth.I_pack_peak_A; dist = 1 ms Forward-Euler integral of
%     |vel_W|; soc_min, T_cell_max running extrema; t_mission from the first MCU AUTO (mode 6).
%   * NaN guard: Relational Operator isFinite -> NOT -> OR, latched, one sample later an Assertion
%     (StopWhenAssertionFail on) stops the run after stop_reason = 5 has been logged.
%   * Stop Simulation on mission done (P.scen.stop_on_mission_done), SoC floor (P.sim.stop_soc) and
%     collision (P.scen.stop_on_collision); stop_reason codes of Bus_SimKPI.
%   * Check Static Range (warnings only): SOC [0 1], T_cell [250 360] K, speed_fwd +/- 3 m/s.
%   Layout: the file saves through shaddad_bu('save'), which lays out every level with shaddad_layout (layout spec 7).
%   Every signal line is named (L5, shaddad_bu('nline')). The root ports stay classic (ICD 3.1), and each consumer of a
%   bus has its own Bus Selector right in front of it (spec 6.2, helper SEL).
%   Idempotent (build plan rule 3).

mdl = 'Sim_Monitors';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'subsystems', 'integration', [mdl '.slx']);
T = build_stubs('table');
R = T(strcmp({T.name}, mdl));
shaddad_bu('fresh', mdl, file, 'ssr');
set_param(mdl, 'Description', ['Simulation monitors: collision / clearance, energy audit, KPIs, NaN guard, ' ...
    'stop conditions (integration spec 4.5). Generated by scripts/build/build_sim_monitors.m - do not edit.']);

s = mdl;
A = @(sys, lib, name, varargin) add_block(lib, [sys '/' name], varargin{:});
Ln = @(sys, src, dst, nm) shaddad_bu('nline', sys, src, dst, nm);
% one consumer's Bus Selector right in front of it (spec 6.2): sigs from the bus line src, output k into dsts{k}
SEL = @(blk, src, sigs, dsts, nm) local_sel(s, blk, src, sigs, dsts, nm);

%% ---- root ports ----
for k = 1:numel(R.in)
    A(s, 'simulink/Sources/In1', R.in(k).name, 'Port', num2str(k), 'OutDataTypeStr', R.in(k).type, ...
        'SampleTime', shaddad_bu('tsexpr', R.in(k).ts));
end
A(s, 'simulink/Sinks/Out1', 'kpi', 'OutDataTypeStr', 'Bus: Bus_SimKPI');

%% ---- rate transitions to the monitor rate (0.1 s) ----
rt = {'truth', 'Bus_TruthState'; 'drive_truth', 'Bus_DriveTruth'; 'obs', 'Bus_ObstaclesDyn'; ...
      'telem', 'Bus_FwTelemetry'; 'gnc_status', 'Bus_GncStatus'; 'struct_diag', 'Bus_StructureDiag'};
for k = 1:size(rt, 1)
    A(s, 'simulink/Signal Attributes/Rate Transition', ['RT_' rt{k, 1}], 'Integrity', 'on', ...
        'Deterministic', 'on', 'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'Ts.monitor', ...
        'InitialCondition', ['P.ic.' rt{k, 2}]);
    Ln(s, [rt{k, 1} '/1'], ['RT_' rt{k, 1} '/1'], rt{k, 1});
end

%% ---- distance travelled: 1 ms integral of |vel_W| ----
A(s, 'simulink/Signal Routing/Bus Selector', 'Sel_vel1k', 'OutputSignals', 'vel_W');
A(s, 'simulink/Math Operations/Dot Product', 'VV');
A(s, 'simulink/Math Operations/Sqrt', 'Speed_abs');
A(s, 'simulink/Discrete/Discrete-Time Integrator', 'Dist_int', 'IntegratorMethod', 'Integration: Forward Euler', ...
    'gainval', '1.0', 'InitialCondition', '0', 'SampleTime', 'Ts.base');
A(s, 'simulink/Signal Attributes/Rate Transition', 'RT_dist', 'Integrity', 'on', 'Deterministic', 'on', ...
    'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'Ts.monitor', 'InitialCondition', '0');
Ln(s, 'truth/1', 'Sel_vel1k/1', 'truth');
Ln(s, 'Sel_vel1k/1', 'VV/1', '');
Ln(s, 'Sel_vel1k/1', 'VV/2', '');
Ln(s, 'VV/1', 'Speed_abs/1', '');
Ln(s, 'Speed_abs/1', 'Dist_int/1', 'speed_abs');
Ln(s, 'Dist_int/1', 'RT_dist/1', '');

%% ---- truth at 0.1 s ----
% Sel_pose feeds the footprint pose below; Sel_truth_guard the NaN guard; Sel_truth_speed the range check

%% ---- footprint pose (navlib Coordinate Transformation Conversion) ----
A(s, 'simulink/Signal Routing/Selector', 'Sel_xy', 'NumberOfDimensions', '1', ...
    'IndexOptions', 'Index vector (dialog)', 'Indices', '[1 2]', 'InputPortWidth', '3');
A(s, 'simulink/Signal Routing/Selector', 'Sel_psi', 'NumberOfDimensions', '1', ...
    'IndexOptions', 'Index vector (dialog)', 'Indices', '3', 'InputPortWidth', '3');
% the block takes Euler angles and translations as 3 x N columns
A(s, 'simulink/Sources/Constant', 'Zero2', 'Value', 'zeros(2,1)', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Sources/Constant', 'Zero1', 'Value', '0', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Math Operations/Reshape', 'Psi_row', 'OutputDimensionality', 'Column vector (2-D)');
A(s, 'simulink/Math Operations/Reshape', 'XY_row', 'OutputDimensionality', 'Column vector (2-D)');
A(s, 'simulink/Math Operations/Matrix Concatenate', 'Eul_fp', 'NumInputs', '2', 'ConcatenateDimension', '1');
A(s, 'simulink/Math Operations/Matrix Concatenate', 'Tr_fp', 'NumInputs', '2', 'ConcatenateDimension', '1');
A(s, 'navlib/Utilities/Coordinate Transformation Conversion', 'Pose_fp', ...
    'InputRepresentation', 'Euler Angles', 'InputEulerSequence', 'ZYX', 'ShowTrVecInputPort', 'on', ...
    'OutputRepresentation', 'Homogeneous Transformation', 'SimulateUsing', 'Interpreted execution');
A(s, 'simulink/Signal Routing/Selector', 'Sel_R2', 'NumberOfDimensions', '2', ...
    'IndexOptions', 'Index vector (dialog),Index vector (dialog)', 'Indices', '[1 2],[1 2]');
A(s, 'simulink/Signal Routing/Selector', 'Sel_p', 'NumberOfDimensions', '2', ...
    'IndexOptions', 'Index vector (dialog),Index vector (dialog)', 'Indices', '[1 2],4');
SEL('Sel_pose', 'RT_truth/1', {'pose2D'}, {{'Sel_xy/1', 'Sel_psi/1'}}, 'truth_10Hz');
Ln(s, 'Sel_psi/1', 'Psi_row/1', '');
Ln(s, 'Psi_row/1', 'Eul_fp/1', '');
Ln(s, 'Zero2/1', 'Eul_fp/2', '');
Ln(s, 'Sel_xy/1', 'XY_row/1', '');
Ln(s, 'XY_row/1', 'Tr_fp/1', '');
Ln(s, 'Zero1/1', 'Tr_fp/2', '');
Ln(s, 'Eul_fp/1', 'Pose_fp/1', 'eul_fp');
Ln(s, 'Tr_fp/1', 'Pose_fp/2', 'trvec_fp');
Ln(s, 'Pose_fp/1', 'Sel_R2/1', 'T_fp');
Ln(s, 'Pose_fp/1', 'Sel_p/1', 'T_fp');
% fp_p (2x1) = Sel_p/1, fp_R (2x2) = Sel_R2/1

%% ---- static cylinders: nearest K_c ----
local_nearest(s, 'Cyl', 'sim_monitor_obstacles(P.world,''cyl'',P.sim.mon)', 3, 'P.sim.mon.Kc', false);
Ln(s, 'Sel_p/1', 'Near_Cyl/1', 'fp_p');
local_foreach(s, 'FE_Cyl', 3, 'circle');
Ln(s, 'Near_Cyl/1', 'FE_Cyl/1', 'cyl_near');
Ln(s, 'Sel_p/1', 'FE_Cyl/2', 'fp_p');
Ln(s, 'Sel_R2/1', 'FE_Cyl/3', 'fp_R');

%% ---- static boxes (incl. film): nearest K_b ----
local_nearest(s, 'Box', 'sim_monitor_obstacles(P.world,''box'',P.sim.mon)', 5, 'P.sim.mon.Kb', true);
Ln(s, 'Sel_p/1', 'Near_Box/1', 'fp_p');
local_foreach(s, 'FE_Box', 5, 'rect');
Ln(s, 'Near_Box/1', 'FE_Box/1', 'box_near');
Ln(s, 'Sel_p/1', 'FE_Box/2', 'fp_p');
Ln(s, 'Sel_R2/1', 'FE_Box/3', 'fp_R');

%% ---- dynamic cylinders (ScenarioIn.obs, rows > n ignored) ----
A(s, 'simulink/Math Operations/Reshape', 'R_col', 'OutputDimensionality', 'Column vector (2-D)');
A(s, 'simulink/Math Operations/Matrix Concatenate', 'Dyn_tab', 'NumInputs', '2', 'ConcatenateDimension', '2');
SEL('Sel_obs_r', 'RT_obs/1', {'r'}, {'R_col/1'}, 'obs_10Hz');
SEL('Sel_obs_xy', 'RT_obs/1', {'xy'}, {'Dyn_tab/1'}, 'obs_10Hz');
Ln(s, 'R_col/1', 'Dyn_tab/2', '');
local_foreach(s, 'FE_Dyn', 3, 'circle');
Ln(s, 'Dyn_tab/1', 'FE_Dyn/1', 'dyn_tab');
Ln(s, 'Sel_p/1', 'FE_Dyn/2', 'fp_p');
Ln(s, 'Sel_R2/1', 'FE_Dyn/3', 'fp_R');
A(s, 'simulink/Sources/Constant', 'Dyn_idx', 'Value', '(1:P.sim.mon.Nd)''', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Signal Attributes/Data Type Conversion', 'N_dbl', 'OutDataTypeStr', 'double');
A(s, 'simulink/Logic and Bit Operations/Relational Operator', 'Dyn_valid', 'Operator', '<=');
A(s, 'simulink/Sources/Constant', 'Far_dyn', 'Value', 'P.sim.mon.far*ones(P.sim.mon.Nd,1)', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Signal Routing/Switch', 'Dyn_sel', 'Criteria', 'u2 ~= 0');
SEL('Sel_obs_n', 'RT_obs/1', {'n'}, {'N_dbl/1'}, 'obs_10Hz');
Ln(s, 'Dyn_idx/1', 'Dyn_valid/1', '');
Ln(s, 'N_dbl/1', 'Dyn_valid/2', '');
Ln(s, 'FE_Dyn/1', 'Dyn_sel/1', '');
Ln(s, 'Dyn_valid/1', 'Dyn_sel/2', 'dyn_valid');
Ln(s, 'Far_dyn/1', 'Dyn_sel/3', '');

%% ---- clearance / collision ----
A(s, 'simulink/Math Operations/MinMax', 'Min_cyl', 'Function', 'min', 'Inputs', '1');
A(s, 'simulink/Math Operations/MinMax', 'Min_box', 'Function', 'min', 'Inputs', '1');
A(s, 'simulink/Math Operations/MinMax', 'Min_dyn', 'Function', 'min', 'Inputs', '1');
A(s, 'simulink/Math Operations/MinMax', 'Sep_now', 'Function', 'min', 'Inputs', '3');
A(s, 'simulink/Math Operations/MinMax', 'Clear_min', 'Function', 'min', 'Inputs', '2');
A(s, 'simulink/Discrete/Unit Delay', 'Clear_prev', 'InitialCondition', 'P.sim.mon.far', 'SampleTime', 'Ts.monitor');
Ln(s, 'FE_Cyl/1', 'Min_cyl/1', 'sep_cyl');
Ln(s, 'FE_Box/1', 'Min_box/1', 'sep_box');
Ln(s, 'Dyn_sel/1', 'Min_dyn/1', 'sep_dyn');
hc = Ln(s, 'Min_cyl/1', 'Sep_now/1', 'mon_sep_cyl');
hb = Ln(s, 'Min_box/1', 'Sep_now/2', 'mon_sep_box');
hd = Ln(s, 'Min_dyn/1', 'Sep_now/3', 'mon_sep_dyn');
for h = [hc hb hd], local_log(h); end
Ln(s, 'Sep_now/1', 'Clear_min/1', 'sep_now');
Ln(s, 'Clear_prev/1', 'Clear_min/2', '');
Ln(s, 'Clear_min/1', 'Clear_prev/1', 'clear_min');
A(s, 'simulink/Logic and Bit Operations/Compare To Zero', 'Collision', 'relop', '<=', 'OutDataTypeStr', 'boolean');
A(s, 'simulink/Logic and Bit Operations/Detect Rise Positive', 'Coll_onset', 'vinit', '0');
A(s, 'simulink/Signal Attributes/Data Type Conversion', 'Onset_u16', 'OutDataTypeStr', 'uint16');
A(s, 'simulink/Math Operations/Sum', 'N_coll', 'Inputs', '++', 'OutDataTypeStr', 'uint16', ...
    'SaturateOnIntegerOverflow', 'on');
A(s, 'simulink/Discrete/Unit Delay', 'N_coll_prev', 'InitialCondition', 'uint16(0)', 'SampleTime', 'Ts.monitor');
Ln(s, 'Sep_now/1', 'Collision/1', 'sep_now');
Ln(s, 'Collision/1', 'Coll_onset/1', 'collision');
Ln(s, 'Coll_onset/1', 'Onset_u16/1', '');
Ln(s, 'Onset_u16/1', 'N_coll/1', '');
Ln(s, 'N_coll_prev/1', 'N_coll/2', '');
Ln(s, 'N_coll/1', 'N_coll_prev/1', 'n_coll');

%% ---- energy audit (D40) ----
A(s, 'simulink/Math Operations/Sum', 'E_net_Wh', 'Inputs', '+-');
A(s, 'simulink/Math Operations/Gain', 'E_batt_J', 'Gain', '3600');
A(s, 'simulink/Math Operations/Gain', 'E_regen_J', 'Gain', '3600');
SEL('Sel_pt_net', 'power_truth/1', {'E_out_Wh', 'E_in_Wh'}, {'E_net_Wh/1', 'E_net_Wh/2'}, 'power_truth');
Ln(s, 'E_net_Wh/1', 'E_batt_J/1', '');
SEL('Sel_pt_regen', 'power_truth/1', {'E_in_Wh'}, {'E_regen_J/1'}, 'power_truth');
A(s, 'simulink/Math Operations/Sum', 'El_resid', 'Inputs', '+-+-----');
SEL('Sel_pt_el', 'power_truth/1', {'E_out_Wh', 'E_in_Wh', 'E_chg_bus_Wh', 'E_trac_dc_Wh', 'E_impl_dc_Wh', 'E_lv_Wh', ...
    'E_dcdc_loss_Wh', 'E_pdu_loss_Wh'}, arrayfun(@(k) sprintf('El_resid/%d', k), 1:8, 'UniformOutput', false), 'power_truth');
A(s, 'simulink/Math Operations/Abs', 'El_abs');
A(s, 'simulink/Sources/Constant', 'E_out_min', 'Value', 'P.sim.mon.E_out_min_Wh', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Math Operations/MinMax', 'El_den', 'Function', 'max', 'Inputs', '2');
A(s, 'simulink/Math Operations/Product', 'Eps_el', 'Inputs', '*/');
Ln(s, 'El_resid/1', 'El_abs/1', '');
SEL('Sel_pt_den', 'power_truth/1', {'E_out_Wh'}, {'El_den/1'}, 'power_truth');
Ln(s, 'E_out_min/1', 'El_den/2', '');
Ln(s, 'El_abs/1', 'Eps_el/1', '');
Ln(s, 'El_den/1', 'Eps_el/2', '');
% mechanical: sum(E_spr) - E_diss - (E_mech - E_mech0)
A(s, 'simulink/Math Operations/Sum', 'E_spr_sum', 'Inputs', '++');
A(s, 'simulink/Sources/Constant', 'False_c', 'Value', 'false', 'OutDataTypeStr', 'boolean', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Discrete/Unit Delay', 'First_step', 'InitialCondition', 'true', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Signal Routing/Switch', 'E_mech0', 'Criteria', 'u2 ~= 0');
A(s, 'simulink/Discrete/Unit Delay', 'E_mech0_prev', 'InitialCondition', '0', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Math Operations/Sum', 'Mech_resid', 'Inputs', '+--+');
A(s, 'simulink/Math Operations/Abs', 'Mech_abs');
A(s, 'simulink/Sources/Constant', 'E_spr_min', 'Value', 'P.sim.mon.E_spr_min_J', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Math Operations/MinMax', 'Mech_den', 'Function', 'max', 'Inputs', '2');
A(s, 'simulink/Math Operations/Product', 'Eps_mech', 'Inputs', '*/');
SEL('Sel_dt_spr', 'RT_drive_truth/1', {'L.E_spr', 'R.E_spr'}, {'E_spr_sum/1', 'E_spr_sum/2'}, 'drive_truth_10Hz');
Ln(s, 'False_c/1', 'First_step/1', '');
SEL('Sel_sd_mech0', 'RT_struct_diag/1', {'E_mech'}, {'E_mech0/1'}, 'struct_diag_10Hz');
Ln(s, 'First_step/1', 'E_mech0/2', 'first_step');
Ln(s, 'E_mech0_prev/1', 'E_mech0/3', '');
Ln(s, 'E_mech0/1', 'E_mech0_prev/1', 'E_mech0');
Ln(s, 'E_spr_sum/1', 'Mech_resid/1', 'E_spr_sum');
SEL('Sel_sd_resid', 'RT_struct_diag/1', {'E_diss_J', 'E_mech'}, {'Mech_resid/2', 'Mech_resid/3'}, 'struct_diag_10Hz');
Ln(s, 'E_mech0/1', 'Mech_resid/4', '');
Ln(s, 'Mech_resid/1', 'Mech_abs/1', '');
Ln(s, 'E_spr_sum/1', 'Mech_den/1', '');
Ln(s, 'E_spr_min/1', 'Mech_den/2', '');
Ln(s, 'Mech_abs/1', 'Eps_mech/1', '');
Ln(s, 'Mech_den/1', 'Eps_mech/2', '');

%% ---- running extrema ----
A(s, 'simulink/Math Operations/MinMax', 'Soc_min', 'Function', 'min', 'Inputs', '2');
A(s, 'simulink/Discrete/Unit Delay', 'Soc_min_prev', 'InitialCondition', 'P.sim.mon.far', 'SampleTime', 'Ts.monitor');
A(s, 'simulink/Math Operations/MinMax', 'Tcell_max', 'Function', 'max', 'Inputs', '2');
A(s, 'simulink/Discrete/Unit Delay', 'Tcell_max_prev', 'InitialCondition', '-P.sim.mon.far', 'SampleTime', 'Ts.monitor');
SEL('Sel_pt_soc', 'power_truth/1', {'SOC_pack_true'}, {'Soc_min/1'}, 'power_truth');
Ln(s, 'Soc_min_prev/1', 'Soc_min/2', '');
Ln(s, 'Soc_min/1', 'Soc_min_prev/1', 'soc_min');
SEL('Sel_pt_T', 'power_truth/1', {'T_cell_max_K'}, {'Tcell_max/1'}, 'power_truth');
Ln(s, 'Tcell_max_prev/1', 'Tcell_max/2', '');
Ln(s, 'Tcell_max/1', 'Tcell_max_prev/1', 'T_cell_max');

%% ---- mission timer (first MCU AUTO, ShaddadMode 6) ----
A(s, 'simulink/Signal Routing/Bus Selector', 'Sel_telem', 'OutputSignals', 'mode');
A(s, 'simulink/Logic and Bit Operations/Compare To Constant', 'Is_auto', 'relop', '==', 'const', '6', ...
    'OutDataTypeStr', 'boolean');
A(s, 'simulink/Logic and Bit Operations/Logical Operator', 'Seen_auto', 'Operator', 'OR', 'Inputs', '2');
