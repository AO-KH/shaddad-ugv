function build_tb_frames()
%BUILD_TB_FRAMES  Generate tests/integration/tb_frames.slx, the kinematic frame oracle of T-INT-04 (T16).
%
%   robotmobilelib/Differential Drive Kinematic Model (VehicleInputs 'Wheel Speeds', WheelRadius =
%   P.drive.gear.r_spr, TrackWidth = P.structure.geom.B, InitialState tb_frames_x0) driven by the constant
%   sprocket speeds tb_frames_w = [w_L w_R] (rad/s); root Outport 'state' = [x y theta] (ENU, yaw CCW from
%   East). SimulateUsing 'Interpreted execution' (no C compiler for 'Code generation').
%   tb_frames_w / tb_frames_x0 are passed with Simulink.SimulationInput.setVariable. Idempotent.
%   Layout: the file saves through shaddad_bu('save') (layout spec 7), every signal line named (L5); the model's state
%   derivative, unused here, ends in the Terminator T_stateDot, so no port stays unconnected (spec 8).

mdl = 'tb_frames';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'tests', 'integration', [mdl '.slx']);
shaddad_bu('fresh', mdl, file, 'model');
shaddad_configsets('attach', mdl);
set_param(mdl, 'Description', 'T-INT-04 kinematic frame oracle. Generated by scripts/build/build_tb_frames.m.');
% constant inputs of the continuous kinematic model (one scalar wheel speed per port)
add_block('simulink/Sources/Constant', [mdl '/w_L'], 'Value', 'tb_frames_w(1)', 'SampleTime', 'inf');
add_block('simulink/Sources/Constant', [mdl '/w_R'], 'Value', 'tb_frames_w(2)', 'SampleTime', 'inf');
add_block('robotmobilelib/Differential Drive Kinematic Model', [mdl '/DiffDrive']);
set_param([mdl '/DiffDrive'], 'VehicleInputs', 'Wheel Speeds', 'WheelRadius', 'P.drive.gear.r_spr', ...
    'TrackWidth', 'P.structure.geom.B', 'InitialState', 'tb_frames_x0');
try
    set_param([mdl '/DiffDrive'], 'SimulateUsing', 'Interpreted execution');
catch %#ok<CTCH> parameter name differs between releases: keep the default
end
add_block('simulink/Sinks/Out1', [mdl '/state']);
add_block('simulink/Sinks/Terminator', [mdl '/T_stateDot']);
shaddad_bu('nline', mdl, 'w_L/1', 'DiffDrive/1', 'w_L');
shaddad_bu('nline', mdl, 'w_R/1', 'DiffDrive/2', 'w_R');
shaddad_bu('nline', mdl, 'DiffDrive/1', 'state/1', 'state');
shaddad_bu('nline', mdl, 'DiffDrive/2', 'T_stateDot/1', 'state_dot');
shaddad_bu('save', mdl, file);
end
