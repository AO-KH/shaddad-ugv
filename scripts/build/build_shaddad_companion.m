function build_shaddad_companion()
%BUILD_SHADDAD_COMPANION  Generate models/Shaddad_Companion.slx (D38; ICD 3.1 Companion table; build plan T01.6).
%
%   The single deployable companion (Jetson) top: Model reference with ConfigSetRef Shaddad_Ref and root
%   ports equal to the GNC_Variant ports of Shaddad_System (9 inputs, 6 outputs, build_stubs('table')).
%   Contents: Companion_IO (SSR companion_io, CAN-FD codecs / ROS 2 IO variant), Model blocks NavFusion
%   (Shaddad_NavFusion), Perception (Shaddad_Perception), GNC (Shaddad_GNC, 6 inputs, no plan port, D57),
%   the 10 ms Unit Delay on the Perception nav_state input (explicit loop breaker, arch 6.2, IC
%   P.ic.Bus_NavState) and Signal Specification blocks in front of every Model-block input.
%   Lines are named as in ICD 3.1 (the decoded MCU status is 'mcu_status_dec', the name of the
%   companion_io output port, because 'mcu_status' is also the CAN-FD frame input); a Signal Specification's output line
%   carries the name of the signal it specifies (layout spec 6.1, L5). The root ports stay classic (spec 6.4); the file is
%   saved through shaddad_bu('save'), which lays it out and puts each Signal Specification next to its port (L4).
%   Idempotent: closes, deletes and regenerates the file (build plan rule 3).

mdl = 'Shaddad_Companion';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'models', [mdl '.slx']);
T = build_stubs('table');
R = T(strcmp({T.name}, mdl));
if bdIsLoaded('Shaddad_System'), close_system('Shaddad_System', 0); end   % parent (integration-owned)
shaddad_bu('fresh', mdl, file, 'model');
shaddad_configsets('attach', mdl);
set_param(mdl, 'Description', ['Shaddad companion computer top (NavFusion + Perception + GNC + CAN-FD IO), ' ...
    'D38. Generated by scripts/build/build_shaddad_companion.m - do not edit by hand.']);
A = @(lib, name, varargin) shaddad_bu('add', lib, [mdl '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('nline', mdl, src, dst, nm);

%% ---- root ports (= GNC_Variant ports, ICD 3.1) ----
for k = 1:numel(R.in)
    p = R.in(k);
    A('simulink/Sources/In1', p.name, 'Port', num2str(k), 'OutDataTypeStr', p.type, ...
        'SampleTime', shaddad_bu('tsexpr', p.ts), 'BusOutputAsStruct', 'on');
end
for k = 1:numel(R.out)
    p = R.out(k);
    A('simulink/Sinks/Out1', p.name, 'Port', num2str(k), 'OutDataTypeStr', p.type, ...
        'SampleTime', shaddad_bu('tsexpr', p.ts), 'BusOutputAsStruct', 'on');
end

%% ---- Companion_IO (SSR companion_io) and the three companion models ----
A('simulink/Ports & Subsystems/Subsystem Reference', 'Companion_IO', 'ReferencedSubsystem', 'companion_io');
A('simulink/Ports & Subsystems/Model', 'NavFusion', 'ModelName', 'Shaddad_NavFusion', 'SimulationMode', 'Normal');
A('simulink/Ports & Subsystems/Model', 'Perception', 'ModelName', 'Shaddad_Perception', 'SimulationMode', 'Normal');
A('simulink/Ports & Subsystems/Model', 'GNC', 'ModelName', 'Shaddad_GNC', 'SimulationMode', 'Normal');
A('simulink/Discrete/Unit Delay', 'NavState_Delay', 'InitialCondition', 'P.ic.Bus_NavState', ...
    'SampleTime', 'Ts.nav');

%% ---- Signal Specification in front of every Model-block input (none is driven by a Bus Creator) ----
specs = {T(strcmp({T.name}, 'Shaddad_NavFusion')), 'NavFusion'; ...
         T(strcmp({T.name}, 'Shaddad_Perception')), 'Perception'; ...
         T(strcmp({T.name}, 'Shaddad_GNC')), 'GNC'};
% the signal each Spec_<block>_<port> carries on to the Model-block input: the name of the line that feeds it (L5)
sig = struct('NavFusion_imu', 'imu_meas', 'NavFusion_odom', 'odom_meas', 'NavFusion_gnss', 'gnss_raw', ...
    'NavFusion_scanmatch', 'scanmatch', 'NavFusion_navcmd', 'nav_cmd', 'NavFusion_bms', 'bms_status', ...
    'Perception_scan', 'lidar_scan', 'Perception_cloud', 'lidar_cloud', 'Perception_nav_state', 'nav_state_z1', ...
    'GNC_nav_state', 'nav_state', 'GNC_perception', 'perception', 'GNC_mcu_status', 'mcu_status_dec', ...
    'GNC_bms_status', 'bms_status', 'GNC_mcmd', 'mcmd', 'GNC_spray', 'spray');
for s = 1:size(specs, 1)
    Rm = specs{s, 1}; blk = specs{s, 2};
    for k = 1:numel(Rm.in)
        p = Rm.in(k);
        nm = sprintf('Spec_%s_%s', blk, p.name);
        A('simulink/Signal Attributes/Signal Specification', nm, 'OutDataTypeStr', p.type, ...
            'SampleTime', shaddad_bu('tsexpr', p.ts), 'BusOutputAsStruct', 'on');   % require nonvirtual bus
        L([nm '/1'], sprintf('%s/%d', blk, k), sig.(extractAfter(nm, 'Spec_')));
    end
end

%% ---- lines (ICD 3.1 Companion table) ----
% Companion_IO: in 1 mcu_imu, 2 mcu_odom, 3 mcu_status, 4 mcu_power, 5 gnc_cmd
%               out 1 imu_meas, 2 odom_meas, 3 mcu_status_dec, 4 bms_status, 5 comp_cmd
L('mcu_imu/1', 'Companion_IO/1', 'mcu_imu');
L('mcu_odom/1', 'Companion_IO/2', 'mcu_odom');
L('mcu_status/1', 'Companion_IO/3', 'mcu_status');
L('mcu_power/1', 'Companion_IO/4', 'mcu_power');
L('Companion_IO/5', 'comp_cmd/1', 'comp_cmd');
L('Companion_IO/1', 'Spec_NavFusion_imu/1', 'imu_meas');
L('Companion_IO/2', 'Spec_NavFusion_odom/1', 'odom_meas');
L('Companion_IO/3', 'Spec_GNC_mcu_status/1', 'mcu_status_dec');
L('Companion_IO/4', 'Spec_NavFusion_bms/1', 'bms_status');
L('Companion_IO/4', 'Spec_GNC_bms_status/1', 'bms_status');
% NavFusion: in 1 imu, 2 odom, 3 gnss, 4 scanmatch, 5 navcmd, 6 bms; out 1 nav_state, 2 nav_diag
L('gnss_raw/1', 'Spec_NavFusion_gnss/1', 'gnss_raw');
L('NavFusion/1', 'nav_state/1', 'nav_state');
L('NavFusion/1', 'Spec_GNC_nav_state/1', 'nav_state');
L('NavFusion/1', 'NavState_Delay/1', 'nav_state');
L('NavFusion/2', 'nav_diag/1', 'nav_diag');
% Perception: in 1 scan, 2 cloud, 3 nav_state (through the 10 ms Unit Delay); out 1 perception, 2 scanmatch
L('lidar_scan/1', 'Spec_Perception_scan/1', 'lidar_scan');
L('lidar_cloud/1', 'Spec_Perception_cloud/1', 'lidar_cloud');
L('NavState_Delay/1', 'Spec_Perception_nav_state/1', 'nav_state_z1');
L('Perception/1', 'perception/1', 'perception');
L('Perception/1', 'Spec_GNC_perception/1', 'perception');
L('Perception/2', 'Spec_NavFusion_scanmatch/1', 'scanmatch');
% GNC: in 1 nav_state, 2 perception, 3 mcu_status, 4 bms_status, 5 mcmd, 6 spray
%      out 1 gnc_cmd, 2 nav_cmd, 3 gnc_status, 4 gnc_debug
L('mcmd/1', 'Spec_GNC_mcmd/1', 'mcmd');
L('spray/1', 'Spec_GNC_spray/1', 'spray');
L('GNC/1', 'Companion_IO/5', 'gnc_cmd');
L('GNC/2', 'Spec_NavFusion_navcmd/1', 'nav_cmd');
L('GNC/3', 'gnc_status/1', 'gnc_status');
L('GNC/4', 'gnc_debug/1', 'gnc_debug');

shaddad_bu('save', mdl, file);
shaddad_bu('finalize', mdl, file);
end
