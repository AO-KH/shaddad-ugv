function build_viz_logging()
%BUILD_VIZ_LOGGING  Generate subsystems/integration/Viz_Logging.slx (Subsystem Reference, build plan T16.2).
%
%   Ports (ICD 3.1): 1 truth (Bus_TruthState, 1 ms), 2 nav_state (0.01), 3 gnc_status (0.2),
%   4 perception (0.1), 5 telem (Bus_FwTelemetry, 0.01), 6 indicators (0.1); no outputs.
%   Variant Subsystem Viz_Variant on VC_VIZ ('update diagram'):
%     VC_VIZ == 0  None     : Terminators (batch runs, accelerator, rapid accelerator)
%     VC_VIZ == 1  BEV      : MATLAB System shaddad.BirdsEyeView (Interpreted execution, 0.1 s) fed through
%                             deterministic Rate Transitions: truth pose2D, NavState [x y psi], perception
%                             ranges / angles, telem mode / SOC; map, footprint, trail and the compiled
%                             mission path from P (integration spec 5.1)
%     VC_VIZ == 2  XY       : simulink/Sinks/XY Graph truth x-y and NavState x-y at 0.1 s
%     VC_VIZ == 3  Robot3D  : MATLAB System shaddad.Robot3DView (live 3-D robot, P.viz.Ts3d), live RC drive
%   Signal logging of the system signals is configured on the Shaddad_System lines (build_shaddad_system,
%   decimation by run_scenario / scn_base_input). Idempotent (build plan rule 3).
%   Layout: the file saves through shaddad_bu('save'), which lays out every level with shaddad_layout (layout spec 7), and
%   every signal line is named (L5, shaddad_bu('nline')). The root ports and those of the four VC_VIZ choices stay classic
%   and identical (ICD 3.1, rule 6).

mdl = 'Viz_Logging';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'subsystems', 'integration', [mdl '.slx']);
T = build_stubs('table');
R = T(strcmp({T.name}, mdl));
shaddad_bu('fresh', mdl, file, 'ssr');
set_param(mdl, 'Description', ['Live visualisation variants (VC_VIZ 0 none / 1 bird''s-eye view / 2 XY Graph / 3 3-D robot). ' ...
    'Generated by scripts/build/build_viz_logging.m - do not edit.']);
for k = 1:numel(R.in)
    add_block('simulink/Sources/In1', [mdl '/' R.in(k).name], 'Port', num2str(k), 'OutDataTypeStr', R.in(k).type, ...
        'SampleTime', shaddad_bu('tsexpr', R.in(k).ts));
end

%% ---- Viz_Variant ----
v = [mdl '/Viz_Variant'];
add_block('simulink/Ports & Subsystems/Variant Subsystem', v);
ch = find_system(v, 'MatchFilter', @Simulink.match.allVariants, 'SearchDepth', 1);
ch = setdiff(ch, {v});
for k = 1:numel(ch), delete_block(ch{k}); end
for k = 1:numel(R.in)
    add_block('simulink/Sources/In1', [v '/' R.in(k).name], 'Port', num2str(k));
end
local_none([v '/None'], R);
local_bev([v '/BEV'], R);
local_xy([v '/XY'], R);
local_robot3d([v '/Robot3D'], R);
set_param([v '/None'], 'VariantControl', 'VC_VIZ == 0');
set_param([v '/BEV'], 'VariantControl', 'VC_VIZ == 1');
set_param([v '/XY'], 'VariantControl', 'VC_VIZ == 2');
set_param([v '/Robot3D'], 'VariantControl', 'VC_VIZ == 3');
set_param(v, 'VariantControlMode', 'expression', 'VariantActivationTime', 'update diagram');
for k = 1:numel(R.in)
    shaddad_bu('nline', mdl, [R.in(k).name '/1'], sprintf('Viz_Variant/%d', k), R.in(k).name);
end
shaddad_bu('save', mdl, file);
end

% ===========================================================================================
function s = local_choice(s, R)
add_block('simulink/Ports & Subsystems/Subsystem', s);
delete_line(s, 'In1/1', 'Out1/1');
delete_block([s '/In1']); delete_block([s '/Out1']);
for k = 1:numel(R.in)
    add_block('simulink/Sources/In1', [s '/' R.in(k).name], 'Port', num2str(k), 'OutDataTypeStr', R.in(k).type);
end
end

function local_none(s, R)
local_choice(s, R);
for k = 1:numel(R.in)
    add_block('simulink/Sinks/Terminator', [s '/Term_' R.in(k).name]);
    shaddad_bu('nline', s, [R.in(k).name '/1'], ['Term_' R.in(k).name '/1'], R.in(k).name);
end
set_param(s, 'Description', 'VC_VIZ == 0: no live visualisation.');
end

function local_bev(s, R)
local_choice(s, R);
A = @(name, lib, varargin) add_block(lib, [s '/' name], varargin{:});
Ln = @(src, dst, nm) shaddad_bu('nline', s, src, dst, nm);
RT = @(name, ic) A(name, 'simulink/Signal Attributes/Rate Transition', 'Integrity', 'on', 'Deterministic', 'on', ...
    'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'P.viz.Ts', 'InitialCondition', ic);
RT('RT_truth', 'P.ic.Bus_TruthState');
RT('RT_nav', 'P.ic.Bus_NavState');
RT('RT_telem', 'P.ic.Bus_FwTelemetry');
Ln('truth/1', 'RT_truth/1', 'truth');
Ln('nav_state/1', 'RT_nav/1', 'nav_state');
Ln('telem/1', 'RT_telem/1', 'telem');
A('Sel_truth', 'simulink/Signal Routing/Bus Selector', 'OutputSignals', 'pose2D');
A('Sel_nav', 'simulink/Signal Routing/Bus Selector', 'OutputSignals', 'pos_W,eul');
A('Sel_per', 'simulink/Signal Routing/Bus Selector', 'OutputSignals', 'ranges_B,angles_B');
A('Sel_telem', 'simulink/Signal Routing/Bus Selector', 'OutputSignals', 'mode,SOC');
Ln('RT_truth/1', 'Sel_truth/1', 'truth_viz');
Ln('RT_nav/1', 'Sel_nav/1', 'nav_viz');
Ln('perception/1', 'Sel_per/1', 'perception');
Ln('RT_telem/1', 'Sel_telem/1', 'telem_viz');
A('Sel_xy', 'simulink/Signal Routing/Selector', 'NumberOfDimensions', '1', 'IndexOptions', 'Index vector (dialog)', ...
    'Indices', '[1 2]', 'InputPortWidth', '3');
A('Sel_yaw', 'simulink/Signal Routing/Selector', 'NumberOfDimensions', '1', 'IndexOptions', 'Index vector (dialog)', ...
    'Indices', '1', 'InputPortWidth', '3');
A('Pose_est', 'simulink/Signal Routing/Vector Concatenate', 'NumInputs', '2');
Ln('Sel_nav/1', 'Sel_xy/1', '');
Ln('Sel_nav/2', 'Sel_yaw/1', '');
Ln('Sel_xy/1', 'Pose_est/1', '');
Ln('Sel_yaw/1', 'Pose_est/2', '');
A('BEV', 'simulink/User-Defined Functions/MATLAB System', 'System', 'shaddad.BirdsEyeView');
set_param([s '/BEV'], 'MapImage', 'P.world.occ.grid', 'MapResolution', 'P.world.occ.res', ...
    'MapOrigin', 'P.world.occ.origin', 'Footprint', 'P.viz.footprint', 'TrailLength', 'P.viz.trail_len', ...
    'ScanDecim', 'P.viz.scan_decim', 'SampleTime', 'P.viz.Ts', ...
    'PathXY', 'shaddad.BirdsEyeView.planPath(P.gnc.mission)');
Ln('Sel_truth/1', 'BEV/1', '');
Ln('Pose_est/1', 'BEV/2', 'pose_est');
Ln('Sel_per/1', 'BEV/3', '');
Ln('Sel_per/2', 'BEV/4', '');
Ln('Sel_telem/1', 'BEV/5', '');
Ln('Sel_telem/2', 'BEV/6', '');
for nm = {'gnc_status', 'indicators'}
    A(['Term_' nm{1}], 'simulink/Sinks/Terminator');
    Ln([nm{1} '/1'], ['Term_' nm{1} '/1'], nm{1});
end
set_param(s, 'Description', 'VC_VIZ == 1: live bird''s-eye view (shaddad.BirdsEyeView, Interpreted execution, 0.1 s).');
end

