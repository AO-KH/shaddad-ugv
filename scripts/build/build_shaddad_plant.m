function build_shaddad_plant()
%BUILD_SHADDAD_PLANT  Generate models/Shaddad_Plant.slx (ICD 3.2; build plan T01.4).
%
%   Plant Model Reference with every Simscape network of the robot: Subsystem References Structure
%   (structure_plant), Power (Power_Plant), Drive (drive_system), Electronics (Electronics_Plant);
%   Plant_In (scenario re-timing and the drive fault mapping of architecture 6.3); one Solver
%   Configuration on the DC48_TracL_n line (local Backward Euler, P.sim.ssc.*); Zero-Order Holds
%   before root outports fed by continuous signals (truth, tracks 0.001; struct_diag 0.01).
%   Idempotent: closes, deletes and regenerates the file. Uses shaddad_bu helpers.
%   Layout (model layout spec 6.4 and 7): no block is placed here; shaddad_bu('save') lays out the root and
%   Plant_In with shaddad_layout(mdl, 'Recursive', true), the DC48 lines, springs, implement shaft and Solver
%   Configuration in the physical band below the signal flow. The root ports stay classic (ICD 3.1); the scenario
%   elements Plant_In uses are picked by the Bus Selector Sel_scen right in front of it, env's T_amb by Sel_T_amb
%   in front of Drive. Every signal line is named (L5).

mdl = 'Shaddad_Plant';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'models', [mdl '.slx']);
T = build_stubs('table');
R = T(strcmp({T.name}, mdl));
for m = {'Shaddad_System'}
    if bdIsLoaded(m{1}), close_system(m{1}, 0); end   % parent of the plant (integration-owned)
end
shaddad_bu('fresh', mdl, file, 'model');
shaddad_configsets('attach', mdl);
set_param(mdl, 'Description', ['Shaddad UGV plant: all Simscape networks (ICD 2, 3.2). Generated by ' ...
    'scripts/build/build_shaddad_plant.m - do not edit by hand.']);
A = @(lib, name, varargin) shaddad_bu('add', lib, [mdl '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('nline', mdl, src, dst, nm);

%% ---- root ports (ICD 3.1 Plant row) ----
for k = 1:numel(R.in)
    p = R.in(k);
    A('simulink/Sources/In1', p.name, 'Port', num2str(k), 'OutDataTypeStr', p.type, ...
        'SampleTime', shaddad_bu('tsexpr', p.ts), 'BusOutputAsStruct', 'on');
end
for k = 1:numel(R.out)
    p = R.out(k);
    A('simulink/Sinks/Out1', p.name, 'Port', num2str(k), 'OutDataTypeStr', p.type, ...
        'SampleTime', shaddad_bu('tsexpr', p.ts), 'BusOutputAsStruct', 'on');
end

%% ---- Plant_In: re-timing and fault mapping (architecture 6.3, D62) ----
local_plant_in([mdl '/Plant_In']);

%% ---- domain Subsystem References ----
A('simulink/Ports & Subsystems/Subsystem Reference', 'Structure', 'ReferencedSubsystem', 'structure_plant');
A('simulink/Ports & Subsystems/Subsystem Reference', 'Power', 'ReferencedSubsystem', 'Power_Plant');
A('simulink/Ports & Subsystems/Subsystem Reference', 'Drive', 'ReferencedSubsystem', 'drive_system');
A('simulink/Ports & Subsystems/Subsystem Reference', 'Electronics', 'ReferencedSubsystem', 'Electronics_Plant');
A('simulink/Sources/Constant', 'EnvDisturbance', 'Value', 'P.ic.Bus_EnvDisturbance', ...
    'OutDataTypeStr', 'Bus: Bus_EnvDisturbance', 'SampleTime', 'Ts.base');
A('simulink/Signal Routing/Bus Selector', 'Sel_T_amb', 'OutputSignals', 'T_amb');

%% ---- Zero-Order Holds before root outports fed by continuous signals ----
A('simulink/Discrete/Zero-Order Hold', 'ZOH_truth', 'SampleTime', 'Ts.base');
A('simulink/Discrete/Zero-Order Hold', 'ZOH_tracks', 'SampleTime', 'Ts.base');
A('simulink/Discrete/Zero-Order Hold', 'ZOH_struct_diag', 'SampleTime', 'Ts.ctrl');

%% ---- Solver Configuration (exactly one, on DC48_TracL_n, ICD 2) ----
A(sprintf('nesl_utility/Solver\nConfiguration'), 'Solver Configuration', 'UseLocalSolver', 'on', ...
    'LocalSolverChoice', 'NE_BACKWARD_EULER_ADVANCER', 'LocalSolverSampleTime', 'P.sim.ssc.Ts', ...
    'DoFixedCost', 'on', 'MaxNonlinIter', 'P.sim.ssc.MaxNonlinIter', 'MaxModeIter', 'P.sim.ssc.MaxModeIter');

%% ---- signal lines (ICD 3.2) ----
% Plant_In inputs: 1 scen_hmi, 2 scen_flt, 3 scen_env, picked from scen right in front of it (layout spec 6.4)
A('simulink/Signal Routing/Bus Selector', 'Sel_scen', 'OutputSignals', 'hmi,flt,env');
L('scen/1', 'Sel_scen/1', 'scen');
for k = 1:3, L(sprintf('Sel_scen/%d', k), sprintf('Plant_In/%d', k), ''); end
% Plant_In outputs: 1 hmi, 2 flt, 3 drv_flt, 4 env_ovr
L('Plant_In/1', 'Power/1', 'hmi');            L('Plant_In/1', 'Electronics/4', 'hmi');
L('Plant_In/2', 'Power/8', 'flt');            L('Plant_In/2', 'Electronics/7', 'flt');
L('Plant_In/3', 'Drive/4', 'drv_flt');
L('Plant_In/4', 'Structure/3', 'env_ovr');
% Structure: in 1 impl_cmd, 2 env_dist, 3 env_ovr; out 1 truth, 2 tracks, 3 impl_mech, 4 env, 5 diag
L('Electronics/5', 'Structure/1', 'impl_cmd');
L('EnvDisturbance/1', 'Structure/2', 'env_dist');
L('Structure/1', 'ZOH_truth/1', 'truth');          L('ZOH_truth/1', 'truth/1', 'truth');
L('Structure/2', 'ZOH_tracks/1', 'tracks');        L('ZOH_tracks/1', 'tracks/1', 'tracks');
L('Structure/3', 'Power/6', 'impl_mech');          L('Structure/3', 'Electronics/6', 'impl_mech');
L('Structure/3', 'impl_mech/1', 'impl_mech');
L('Structure/4', 'Power/5', 'env');                L('Structure/4', 'Electronics/5', 'env');
L('Structure/4', 'Sel_T_amb/1', 'env');            L('Structure/4', 'env/1', 'env');
L('Structure/5', 'ZOH_struct_diag/1', 'struct_diag'); L('ZOH_struct_diag/1', 'struct_diag/1', 'struct_diag');
% Power: in 1 hmi, 2 hw_cmd, 3 lv_demand, 4 bms_cmd, 5 env, 6 impl_mech, 7 can_rx, 8 flt
%        out 1 bms_meas, 2 power_status, 3 impl_elec, 4 can_tx, 5 power_truth, 6 safety_ok
L('Electronics/4', 'Power/2', 'hw_cmd');
L('Electronics/6', 'Power/3', 'lv_demand');
L('bms_cmd/1', 'Power/4', 'bms_cmd');
L('can_mcu_slow/1', 'Power/7', 'can_mcu_slow');
L('Power/1', 'bms_meas/1', 'bms_meas');
L('Power/2', 'Electronics/3', 'power_status');     L('Power/2', 'power_status/1', 'power_status');
L('Power/3', 'impl_elec/1', 'impl_elec');
L('Power/4', 'can_impl/1', 'can_impl');
L('Power/5', 'power_truth/1', 'power_truth');
L('Power/6', 'Drive/2', 'safety_ok');
% Drive: in 1 can_rx, 2 sto_ok, 3 T_amb, 4 fault_inj; out 1 can_tx_fast, 2 can_tx_slow, 3 truth
L('can_mcu_fast/1', 'Drive/1', 'can_mcu_fast');
L('Sel_T_amb/1', 'Drive/3', 'T_amb');
L('Drive/1', 'can_esc_fast/1', 'can_esc_fast');
L('Drive/2', 'can_esc_slow/1', 'can_esc_slow');
L('Drive/3', 'drive_truth/1', 'drive_truth');
% Electronics: in 1 mcu_out1k, 2 mcu_out10, 3 power_status, 4 hmi, 5 env, 6 impl_mech, 7 flt
%              out 1 elec_hw, 2 elec_adc, 3 elec_env, 4 hw_cmd, 5 impl_cmd, 6 lv_demand, 7 indicators
L('mcu_out1k/1', 'Electronics/1', 'mcu_out1k');
L('mcu_out10/1', 'Electronics/2', 'mcu_out10');
L('Electronics/1', 'elec_hw/1', 'elec_hw');
L('Electronics/2', 'elec_adc/1', 'elec_adc');
L('Electronics/3', 'elec_env/1', 'elec_env');
L('Electronics/7', 'indicators/1', 'indicators');

%% ---- physical lines (ICD 2) by Connection Port name ----
P = @(blk, port) shaddad_bu('pport', [mdl '/' blk], port);
for nm = {'DC48_TracL_p', 'DC48_TracL_n', 'DC48_TracR_p', 'DC48_TracR_n'}
    shaddad_bu('pline', mdl, P('Power', nm{1}), P('Drive', nm{1}));
end
shaddad_bu('pline', mdl, P('Drive', 'Spr_L'), P('Structure', 'Spr_L'));
shaddad_bu('pline', mdl, P('Drive', 'Spr_R'), P('Structure', 'Spr_R'));
shaddad_bu('pline', mdl, P('Power', 'Impl_Shaft'), P('Structure', 'Impl_Shaft'));
sc = get_param([mdl '/Solver Configuration'], 'PortHandles');
shaddad_bu('pline', mdl, sc.RConn(1), P('Drive', 'DC48_TracL_n'));

shaddad_bu('save', mdl, file);
shaddad_bu('finalize', mdl, file);
end

% -------------------------------------------------------------------------------------------
function local_plant_in(s)
% Plant_In (virtual): scen_hmi -> hmi (0.01 -> 0.001), scen_flt -> flt (0.01 -> 0.001) and drv_flt
% (Bus_DriveFaultInj at 0.001, architecture 6.3), scen_env -> env_ovr (0.01 -> 0.1); the root picks the three
% scenario elements in front of it (Sel_scen). Deterministic RTs (D32); the +10 ms of the slow-to-fast
% transfer is the documented plant-side hmi delay (D62). Laid out at save (no placement here).
add_block('simulink/Ports & Subsystems/Subsystem', s);
delete_line(s, 'In1/1', 'Out1/1');
delete_block([s '/In1']); delete_block([s '/Out1']);
A = @(lib, name, varargin) shaddad_bu('add', lib, [s '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('nline', s, src, dst, nm);
ins = {'scen_hmi', 'Bus: Bus_HmiInputs'; 'scen_flt', 'Bus: Bus_FaultInject'; 'scen_env', 'Bus: Bus_EnvOverride'};
for k = 1:size(ins, 1)
    A('simulink/Sources/In1', ins{k, 1}, 'Port', num2str(k), 'OutDataTypeStr', ins{k, 2}, 'SampleTime', 'Ts.scen');
end
outs = {'hmi', 'Bus: Bus_HmiInputs'; 'flt', 'Bus: Bus_FaultInject'; 'drv_flt', 'Bus: Bus_DriveFaultInj'; ...
        'env_ovr', 'Bus: Bus_EnvOverride'};
for k = 1:size(outs, 1)
    A('simulink/Sinks/Out1', outs{k, 1}, 'Port', num2str(k), 'OutDataTypeStr', outs{k, 2});
end
A('simulink/Signal Attributes/Rate Transition', 'RT_hmi', 'Integrity', 'on', 'Deterministic', 'on', ...
    'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'Ts.base', 'InitialCondition', 'P.ic.Bus_HmiInputs');
A('simulink/Signal Attributes/Rate Transition', 'RT_flt', 'Integrity', 'on', 'Deterministic', 'on', ...
    'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'Ts.base', 'InitialCondition', 'P.ic.Bus_FaultInject');
A('simulink/Signal Attributes/Rate Transition', 'RT_env', 'Integrity', 'on', 'Deterministic', 'on', ...
    'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'Ts.env', 'InitialCondition', 'P.ic.Bus_EnvOverride');
L('scen_hmi/1', 'RT_hmi/1', 'scen_hmi');   L('RT_hmi/1', 'hmi/1', 'hmi');
L('scen_flt/1', 'RT_flt/1', 'scen_flt');   L('RT_flt/1', 'flt/1', 'flt');
L('scen_env/1', 'RT_env/1', 'scen_env');   L('RT_env/1', 'env_ovr/1', 'env_ovr');
% ---- drive fault mapping (1 ms): enc_fail, brake_stuck, tau_scale = 1 - double(motor_fault), can_drop, T_offset;
% a Bus Selector of flt in front of each consumer (layout spec 6.2) ----
A('simulink/Sources/Constant', 'can_drop', 'Value', 'false', 'OutDataTypeStr', 'boolean', 'SampleTime', 'Ts.base');
A('simulink/Sources/Constant', 'T_offset', 'Value', 'P.ic.Bus_DriveSideFaultInj.T_offset', ...
    'OutDataTypeStr', 'double', 'SampleTime', 'Ts.base');
sides = {'L', 'R'};
for k = 1:2
    sd = sides{k};
    A('simulink/Logic and Bit Operations/Logical Operator', ['NOT_motor_' sd], 'Operator', 'NOT');
    A('simulink/Signal Attributes/Data Type Conversion', ['tau_scale_' sd], 'OutDataTypeStr', 'double');
    A('simulink/Signal Routing/Bus Creator', ['BC_' sd], 'Inputs', '5', ...
        'OutDataTypeStr', 'Bus: Bus_DriveSideFaultInj', 'NonVirtualBus', 'on');
    % Bus Selector output lines cannot be renamed: a Signal Conversion (signal copy) carries the
    % bus-object element name (avoids the 'Element name mismatch' diagnostic at the Bus Creator)
    A('simulink/Signal Attributes/Signal Conversion', ['enc_fail_' sd]);
    A('simulink/Signal Attributes/Signal Conversion', ['brake_stuck_' sd]);
    for el = {'enc_fault_', 'enc_fail_'; 'brake_stuck_', 'brake_stuck_'; 'motor_fault_', 'NOT_motor_'}'
        A('simulink/Signal Routing/Bus Selector', ['Sel_' el{1} sd], 'OutputSignals', [el{1} sd]);
        L('RT_flt/1', ['Sel_' el{1} sd '/1'], 'flt');
        L(['Sel_' el{1} sd '/1'], [el{2} sd '/1'], '');
    end
    L(['enc_fail_' sd '/1'], ['BC_' sd '/2'], 'enc_fail');
    L(['brake_stuck_' sd '/1'], ['BC_' sd '/3'], 'brake_stuck');
    L(['NOT_motor_' sd '/1'], ['tau_scale_' sd '/1'], ['motor_ok_' sd]);
    L(['tau_scale_' sd '/1'], ['BC_' sd '/4'], 'tau_scale');
    L('can_drop/1', ['BC_' sd '/1'], 'can_drop');
    L('T_offset/1', ['BC_' sd '/5'], 'T_offset');
end
A('simulink/Signal Routing/Bus Creator', 'BC_drv_flt', 'Inputs', '2', ...
    'OutDataTypeStr', 'Bus: Bus_DriveFaultInj', 'NonVirtualBus', 'on');
L('BC_L/1', 'BC_drv_flt/1', 'L');
L('BC_R/1', 'BC_drv_flt/2', 'R');
L('BC_drv_flt/1', 'drv_flt/1', 'drv_flt');
end
