function build_shaddad_system()
%BUILD_SHADDAD_SYSTEM  Generate models/Shaddad_System.slx, the top model (ICD 3.1; build plan T01.5; layout spec 5).
%
%   Top level (docs/superpowers/specs/2026-11-08-top-level-direct-links-design.md, in place of option A of model
%   layout spec 5): the root In Bus Element ScenarioIn (block In_ScenarioIn, Bus_ScenarioIn, 0.01 s: a bus-object
%   typed bus element port cannot carry a sample time itself, so the Signal Specification Spec_ScenarioIn directly
%   behind it pins Ts.scen and the nonvirtual bus) and the 11 components, joined by direct lines. A component is a
%   virtual Subsystem with one input port per bus that feeds it, named after that bus (In Bus Element blocks, one
%   per signal it picks, named <port>_<element path with _ for .>, or <port>_bus for the whole bus, each showing
%   <port>.<signal>), and one output port named after its bus (Out Bus Element blocks <bus>_<signal>, one per
%   element; Viz_Logging has none). Each
%   link is one virtual bus line from the producer's output to the consumer's port, named after the bus (the table
%   in local_components); scen runs from Spec_ScenarioIn, one line with a branch to each component that reads it;
%   monitors, which nothing reads, ends in the Terminator Term_monitors. A component's main block is named after
%   its file (ports: build_stubs('table')):
%     Operator_Console  operator  OpSource, Variant Source VC_OPSRC: 1 ScenarioIn.op, 2 Dashboard (constants
%                                 bound to dashboard blocks), 3 Joystick, 4 RowDriver (the RC row test driver,
%                                 fed the true pose / speed, MCU mode and tank volume through Rate Transitions
%                                 and Unit Delays)
%     Operator_RC       rc        RC_Link_Sim (Subsystem Reference)
%     MCU               mcu       MCU_In (Bus Creators of Bus_McuIn1k/5/10/50/100, explicit Rate Transitions,
%                                 t_us clock, fault_inject bit word), then Shaddad_MCU (Model, Normal)
%     BMS               bms       Shaddad_BMS (Model, Normal)
%     CAN1_Net          can1      CAN1_Net_Sim (Subsystem Reference)
%     Plant             plant     Shaddad_Plant (Model, Normal)
%     Sensors           sensors   Shaddad_SensorModels (Subsystem Reference)
%     CAN2_Link         can2      Link_MCU_GNC (Subsystem Reference)
%     GNC               gnc       MissionCmd_RT (0.01 -> 0.2, D32), then GNC_Variant (VC_PHASE 1 GNC_Stub,
%                                 2 Companion = Model Shaddad_Companion, D38)
%     Viz_Logging       -         Viz_Logging (Subsystem Reference)
%     Sim_Monitors      monitors  Sim_Monitors (Subsystem Reference)
%   A bus element is the component's ICD 3.1 output name; a consumer picks it, or a sub-element of it (port mcu,
%   element out10.can1_drv; port plant, element truth.pose2D), right in front of the input it feeds. The helpers sit in
%   the component whose timing or interface they model (spec 5.2): a Signal Specification in front of every
%   Model input that no Bus Creator drives; the loop breakers (rule 8, D36) EscFb_Delay, EscSlow_Delay,
%   Impl_Delay, Bms_Delay and Adc_Delay in MCU, BMS_Cmd_Delay in BMS (published as bms.cmd_d), ElecHw_Delay in
%   Plant (published once as plant.elec_hw_d, the word MCU, CAN1 and CAN2 read); the row driver inputs in the
%   console. Every line is named (ICD 3.1; a pick's line after the element it picks, except the console's
%   op_ext, pose, v_fwd and tank_L, named after the input they feed). Signal logging on the ports of
%   scn_logging('table'), with its test decimation. The console's variant region (OpSource, VC_OPSRC) is
%   propagated ungrouped (local_operator_console says why). Layout: the top level as the design's grid
%   (local_place_top), kept by the layout engine at the save (Task 5 decision 9), which re-adds its lines and
%   lays out every subsystem level.
%   Idempotent: closes, deletes and regenerates the file (build plan rule 3).

mdl = 'Shaddad_System';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'models', [mdl '.slx']);
T = build_stubs('table');
row = @(n) T(strcmp({T.name}, n));
shaddad_bu('fresh', mdl, file, 'model');
shaddad_bu('closedirty', {'Shaddad_Companion', 'Shaddad_Plant'});   % unsaved compile state only
shaddad_configsets('attach', mdl);
set_param(mdl, 'Description', ['Shaddad UGV top model (ICD 3.1). Generated by ' ...
    'scripts/build/build_shaddad_system.m - do not edit by hand.']);

%% ---- root input ScenarioIn (In Bus Element, PortName ScenarioIn) ----
h = add_block('simulink/Ports & Subsystems/In Bus Element', [mdl '/In_ScenarioIn']);
set_param(h, 'PortName', 'ScenarioIn', 'Element', '');
set_param(h, 'OutDataTypeStr', 'Bus: Bus_ScenarioIn');
try
    set_param(h, 'BusVirtuality', 'nonvirtual');
catch %#ok<CTCH> attribute owned by the bus object: the Signal Specification below enforces it
end
local_spec(mdl, 'Spec_ScenarioIn', 'Bus: Bus_ScenarioIn', 0.01);
set_param([mdl '/Spec_ScenarioIn'], 'SampleTime', 'Ts.scen');      % P.sim.Ts_scen = 0.01 s
shaddad_bu('line', mdl, 'In_ScenarioIn/1', 'Spec_ScenarioIn/1', 'ScenarioIn');

%% ---- the components, in signal-flow order (spec 5.1); picks in the order of their inputs ----
local_operator_console([mdl '/Operator_Console']);
local_ssr([mdl '/Operator_RC'], 'rc', row('RC_Link_Sim'), {'operator.op', 'scen.flt'});
local_mcu([mdl '/MCU'], row('Shaddad_MCU'));
local_bms([mdl '/BMS'], row('Shaddad_BMS'));
local_ssr([mdl '/CAN1_Net'], 'can1', row('CAN1_Net_Sim'), {'mcu.out10.can1_drv', 'mcu.out50.can1_slow', ...
    'plant.can_esc_fast', 'plant.can_esc_slow', 'plant.can_impl', 'bms.can_tx', 'scen.flt', 'plant.elec_hw_d'});
local_plant([mdl '/Plant'], row('Shaddad_Plant'));
local_ssr([mdl '/Sensors'], 'sensors', row('Shaddad_SensorModels'), {'plant.truth', 'plant.drive_truth', ...
    'plant.env', 'plant.elec_env', 'scen.flt', 'scen.obs'});
local_ssr([mdl '/CAN2_Link'], 'can2', row('Link_MCU_GNC'), {'mcu.out5.can2_imu', 'mcu.out10.can2_odom', ...
    'mcu.out50.can2_status', 'mcu.out100.can2_power', 'gnc.comp_cmd', 'scen.flt', 'plant.elec_hw_d'});
local_gnc([mdl '/GNC'], row('Shaddad_Companion'));
local_ssr([mdl '/Viz_Logging'], '', row('Viz_Logging'), {'plant.truth', 'gnc.nav_state', 'gnc.gnc_status', ...
    'gnc.perception', 'mcu.telem', 'plant.indicators'});
local_ssr([mdl '/Sim_Monitors'], 'monitors', row('Sim_Monitors'), {'plant.truth', 'plant.power_truth', ...
    'plant.drive_truth', 'scen.obs', 'mcu.telem', 'gnc.gnc_status', 'plant.struct_diag'});

%% ---- the links: each input port takes the line of the bus it is named after (scen: from the root) ----
[comp, bus, from] = local_components();
for k = 1:numel(comp)
    s = [mdl '/' comp{k}];
    have = unique(get_param(find_system(s, 'SearchDepth', 1, 'BlockType', 'Inport'), 'PortName'));
    assert(isempty(setxor(have, from{k})), 'build_shaddad_system:links', '%s picks from {%s}, the link table says {%s}', ...
        comp{k}, strjoin(have, ', '), strjoin(from{k}, ', '));
    shaddad_bu('portorder', s, from{k}, 'Inport');
    for j = 1:numel(from{k})
        if strcmp(from{k}{j}, 'scen')
            src = 'Spec_ScenarioIn/1';
        else
            src = [comp{strcmp(bus, from{k}{j})} '/1'];
        end
        shaddad_bu('line', mdl, src, sprintf('%s/%d', comp{k}, j), from{k}{j});
    end
end
% nothing reads monitors: it ends beside its block, so the output stays and no port is left unconnected
shaddad_bu('add', 'simulink/Sinks/Terminator', [mdl '/Term_monitors']);
shaddad_bu('line', mdl, 'Sim_Monitors/1', 'Term_monitors/1', 'monitors');

%% ---- signal logging (T16, integration spec 7.6): test-level decimation on the ports; missions
%      override it with Simulink.SimulationData.ModelLoggingInfo (utilities/scn_logging.m) ----
lg = scn_logging('table');
for k = 1:size(lg, 1)
    ph = get_param([mdl '/' lg{k, 2}], 'PortHandles');
    p = ph.Outport(lg{k, 3});
    set_param(p, 'DataLogging', 'on', 'DataLoggingNameMode', 'Custom', 'DataLoggingName', lg{k, 1}, ...
        'DataLoggingDecimateData', 'on', 'DataLoggingDecimation', num2str(lg{k, 4}));
end

local_place_top(mdl, comp, from);
shaddad_bu('save', mdl, file, struct('Keep', {{mdl}}));   % the engine keeps the top level, lays out the rest
shaddad_bu('finalize', mdl, file);
end

% ===========================================================================================
function [comp, bus, from] = local_components()
% the 11 components in signal-flow order (spec 5.1), the name of each one's output bus ('': none) and its input
% ports, top to bottom: each named after the bus that feeds it, so this table is the list of links (the assert in
% the wiring holds it to the picks)
comp = {'Operator_Console'; 'Operator_RC'; 'MCU'; 'BMS'; 'CAN1_Net'; 'Plant'; 'Sensors'; 'CAN2_Link'; 'GNC'; ...
    'Viz_Logging'; 'Sim_Monitors'};
bus = {'operator'; 'rc'; 'mcu'; 'bms'; 'can1'; 'plant'; 'sensors'; 'can2'; 'gnc'; ''; 'monitors'};
from = {{'scen', 'plant', 'mcu'}; {'scen', 'operator'}; {'scen', 'rc', 'sensors', 'can1', 'plant', 'can2'}; ...
    {'can1', 'plant'}; {'mcu', 'scen', 'plant', 'bms'}; {'mcu', 'scen', 'can1', 'bms'}; {'scen', 'plant'}; ...
    {'scen', 'mcu', 'plant', 'gnc'}; {'scen', 'sensors', 'can2'}; {'mcu', 'plant', 'gnc'}; ...
    {'scen', 'plant', 'mcu', 'gnc'}};
end

function local_place_top(mdl, comp, from)
% a 3 x 4 grid (design 2026-11-08) with the most connected blocks, MCU and Plant, near the middle and most links
% running left to right; the cells and the port order (local_components) are the best of a search with the layout
% engine and its check, every block facing right. ScenarioIn stands above the grid's top left corner; Term_monitors
% beside Sim_Monitors. A block's height follows its input ports. shaddad_bu('save') keeps these positions and adds
% the lines back with smart autorouting (Task 5 decision 9).
G = {'Operator_Console', 1, 1; 'Operator_RC', 2, 1; 'Sensors', 3, 1; 'Sim_Monitors', 4, 1; ...
     'CAN1_Net', 1, 2; 'MCU', 2, 2; 'CAN2_Link', 3, 2; ...
     'BMS', 1, 3; 'Plant', 2, 3; 'Viz_Logging', 3, 3; 'GNC', 4, 3};
x = @(c) 400 + 460*(c - 1);  y = @(r) 240 + 340*(r - 1);  w = 200;   % column left edge, row centre, block width
for k = 1:size(G, 1)
    h = max(60, 30*numel(from{strcmp(comp, G{k, 1})}));
    set_param([mdl '/' G{k, 1}], 'Position', [x(G{k, 2}), y(G{k, 3}) - h/2, x(G{k, 2}) + w, y(G{k, 3}) + h/2]);
end
set_param([mdl '/In_ScenarioIn'], 'Position', [60, 65, 70, 75]);
% the line ScenarioIn runs 90 px from port to port: room for its name label (6 px x 10 characters + 10, the
% engine's estimate, shaddad_layout) clear of both blocks (Task 5 fix round 1, M1)
set_param([mdl '/Spec_ScenarioIn'], 'Position', [160, 55, 240, 85]);
set_param([mdl '/Term_monitors'], 'Position', [x(4) + w + 100, y(1) - 10, x(4) + w + 120, y(1) + 10]);
end

function local_component(s, bus, els)
% an empty virtual Subsystem s with its output port bus: Out Bus Element blocks <bus>_<el>, one per element
% el of els, in that order (the port's first block from the library, the others copied from it: a second
% library block of the same port fails, spec 13); bus '': no output port. local_pick adds its input ports.
add_block('simulink/Ports & Subsystems/Subsystem', s);
delete_line(s, 'In1/1', 'Out1/1');
delete_block([s '/In1']); delete_block([s '/Out1']);
for k = 1:numel(els)
    p = [s '/' bus '_' els{k}];
    if k == 1
        h = add_block('simulink/Ports & Subsystems/Out Bus Element', p);
        set_param(h, 'PortName', bus);
    else
        h = add_block([s '/' bus '_' els{1}], p);
    end
    set_param(h, 'Element', els{k});
end
end

function local_pick(s, el, dst, nm)
% pick el ('<bus>.<signal>', a sub-element, or '<bus>' for the whole bus) from the input port <bus> of component s
% for the input dst ('Block/k'): the In Bus Element block <el with _ for .>, or <bus>_bus for the whole bus (a port
% cannot share its name with a block), the port's first block from the library, the others copied from it; its line
% named nm (default: the element's own name, the last part of el)
p = strrep(el, '.', '_');
if ~contains(el, '.'), p = [el '_bus']; end
[port, sub] = strtok(el, '.');
first = find_system(s, 'SearchDepth', 1, 'BlockType', 'Inport');
first = first(strcmp(get_param(first, 'PortName'), port));
if isempty(first)
    h = add_block('simulink/Ports & Subsystems/In Bus Element', [s '/' p]);
    set_param(h, 'PortName', port);
else
    h = add_block(first{1}, [s '/' p]);
end
set_param(h, 'Element', sub(2:end));
if nargin < 4, nm = regexprep(el, '^.*\.', ''); end
shaddad_bu('line', s, [p '/1'], dst, nm);
end

function local_spec(s, name, type, ts)
% Signal Specification name in s: data type, Ts.<field> sample time and a nonvirtual bus (rule 5)
shaddad_bu('add', 'simulink/Signal Attributes/Signal Specification', [s '/' name], 'OutDataTypeStr', type, ...
    'SampleTime', shaddad_bu('tsexpr', ts), 'BusOutputAsStruct', 'on');
end

function local_ssr(s, bus, R, picks)
% a component around the Subsystem Reference R.name (ports: the build_stubs('table') row R): input k picks
% picks{k}, output k is the element R.out(k).name of the bus
assert(numel(picks) == numel(R.in), 'build_shaddad_system:picks', '%s: %d picks for %d inputs', s, ...
    numel(picks), numel(R.in));
local_component(s, bus, {R.out.name});
shaddad_bu('add', 'simulink/Ports & Subsystems/Subsystem Reference', [s '/' R.name], 'ReferencedSubsystem', R.name);
for k = 1:numel(R.in)
    local_pick(s, picks{k}, sprintf('%s/%d', R.name, k));
end
for k = 1:numel(R.out)
    shaddad_bu('line', s, sprintf('%s/%d', R.name, k), [bus '_' R.out(k).name '/1'], R.out(k).name);
end
end

% -------------------------------------------------------------------------------------------
function local_mcu(s, R)
% MCU_In -> Shaddad_MCU (in 1 in1k .. 5 in100; out 1 out1k, 2 out5, 3 out10, 4 out50, 5 out100, 6 telem).
% MCU_In inputs: 1 sbus, 2 elec_hw (the delayed DI word plant.elec_hw_d), 3 flt, 4 imu_raw, 5 esc_fast_rx,
% 6 esc_slow_rx, 7 impl_rx, 8 comp_cmd_rx, 9 elec_adc, 10 bms_rx (the order of the buses they feed, local_mcu_in)
local_component(s, 'mcu', {R.out.name});
A = @(lib, name, varargin) shaddad_bu('add', lib, [s '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('line', s, src, dst, nm);
local_mcu_in([s '/MCU_In']);
A('simulink/Ports & Subsystems/Model', 'Shaddad_MCU', 'ModelName', 'Shaddad_MCU', 'SimulationMode', 'Normal');
for k = 1:numel(R.in)
    L(sprintf('MCU_In/%d', k), sprintf('Shaddad_MCU/%d', k), R.in(k).name);
end
for k = 1:numel(R.out)
    L(sprintf('Shaddad_MCU/%d', k), ['mcu_' R.out(k).name '/1'], R.out(k).name);
end
local_pick(s, 'rc.sbus', 'MCU_In/1');
local_pick(s, 'plant.elec_hw_d', 'MCU_In/2');
local_pick(s, 'sensors.imu_raw', 'MCU_In/4');
local_pick(s, 'can2.comp_cmd_rx', 'MCU_In/8');
local_pick(s, 'scen.flt', 'MCU_In/3');
% T16 loop breaker (rule 8 / D36): MCU Task_10 is direct feedthrough FB1/FB3 -> DRV_CMD and the plant
% returns FB1/FB3 from DRV_CMD / PWM / LV demand through the Simscape DC bus in the same 10 ms step.
% The ESC feedback frames reach Task_10 one CAN cycle late (frame transmitted during the previous
% period); the command path keeps its D37 latency budget.
% T16 loop breakers for the Task_50 / Task_100 feedback (rule 8 / D36): with an implement (VC_IMPL 1 mower)
% MCU in50 (FB2, IMPL_FB, ADC) -> out50 (BMS_REQ, IMPL_CMD) -> Plant in5 -> Plant out7/8/10 closes an
% artificial 50 ms loop through the monolithic Model blocks. The MCU reads the frame / ADC result of the
% previous period (one-sample acquisition delay); the BMS frames (100 ms) get the same treatment.
fbd = {'EscFb_Delay', 'Bus_Can1_EscFast', 'Ts.ctrl', 'can1.esc_fast_rx', 5; ...
       'EscSlow_Delay', 'Bus_Can1_EscSlow', 'Ts.comm', 'can1.esc_slow_rx', 6; ...
       'Impl_Delay', 'Bus_Can1_Impl', 'Ts.comm', 'can1.impl_rx', 7; ...
       'Bms_Delay', 'Bus_Can1_Bms', 'Ts.hk', 'can1.bms_rx', 10; ...
       'Adc_Delay', 'Bus_ElecAdc', 'Ts.comm', 'plant.elec_adc', 9};
for k = 1:size(fbd, 1)
    A('simulink/Discrete/Unit Delay', fbd{k, 1}, 'InitialCondition', ['P.ic.' fbd{k, 2}], 'SampleTime', fbd{k, 3});
    local_pick(s, fbd{k, 4}, [fbd{k, 1} '/1']);
    L([fbd{k, 1} '/1'], sprintf('MCU_In/%d', fbd{k, 5}), [regexprep(fbd{k, 4}, '^.*\.', '') '_d']);
end
set_param(s, 'Description', ['MCU (ICD 3.1): MCU_In -> Model Shaddad_MCU. The CAN1 feedback frames and the ADC ' ...
    'result reach the MCU one sample late (EscFb/EscSlow/Impl/Bms/Adc_Delay, rule 8, D36).']);
end

function local_bms(s, R)
% Signal Specifications -> Shaddad_BMS (in 1 meas, 2 can_rx; out 1 cmd, 2 can_tx, 3 telem); cmd leaves through
% BMS_Cmd_Delay as the element cmd_d
outs = {R.out.name};
outs{1} = 'cmd_d';
local_component(s, 'bms', outs);
A = @(lib, name, varargin) shaddad_bu('add', lib, [s '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('line', s, src, dst, nm);
A('simulink/Ports & Subsystems/Model', 'Shaddad_BMS', 'ModelName', 'Shaddad_BMS', 'SimulationMode', 'Normal');
src = {'plant.bms_meas', 'can1.mcu_slow_rx'};
for k = 1:numel(R.in)
    sp = ['Spec_BMS_' R.in(k).name];
    local_spec(s, sp, R.in(k).type, R.in(k).ts);
    local_pick(s, src{k}, [sp '/1']);
    L([sp '/1'], sprintf('Shaddad_BMS/%d', k), R.in(k).name);
end
% T16 loop breaker (rule 8 / D36): BMS meas -> cmd is direct feedthrough at 10 ms and the plant returns
% bms_meas from bms_cmd through the Simscape network in the same step, so the BMS ECU output carries its
% one-sample compute delay (P.sim.compute_delay = 1) explicitly; it is published as bms.cmd_d.
A('simulink/Discrete/Unit Delay', 'BMS_Cmd_Delay', 'InitialCondition', 'P.ic.Bus_BMS_Cmd', 'SampleTime', 'Ts.ctrl');
L('Shaddad_BMS/1', 'BMS_Cmd_Delay/1', 'cmd');
L('BMS_Cmd_Delay/1', 'bms_cmd_d/1', 'cmd_d');
for k = 2:numel(R.out)
    L(sprintf('Shaddad_BMS/%d', k), ['bms_' R.out(k).name '/1'], R.out(k).name);
end
set_param(s, 'Description', ['BMS (ICD 3.1): Model Shaddad_BMS; its command leaves through BMS_Cmd_Delay ' ...
    '(the ECU''s one-sample compute delay, rule 8, D36) as bms.cmd_d.']);
end

function local_plant(s, R)
% Signal Specifications -> Shaddad_Plant (in 1 scen, 2 mcu_out1k, 3 mcu_out10, 4 can_mcu_fast, 5 can_mcu_slow,
% 6 bms_cmd; out 1 truth, 2 tracks, 3 drive_truth, 4 power_truth, 5 bms_meas, 6 can_esc_fast, 7 can_esc_slow,
% 8 can_impl, 9 elec_hw, 10 elec_adc, 11 elec_env, 12 env, 13 indicators, 14 impl_mech, 15 impl_elec,
% 16 struct_diag, 17 power_status); elec_hw leaves through ElecHw_Delay as the element elec_hw_d
outs = {R.out.name};
jhw = find(strcmp(outs, 'elec_hw'));
outs{jhw} = 'elec_hw_d';
local_component(s, 'plant', outs);
A = @(lib, name, varargin) shaddad_bu('add', lib, [s '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('line', s, src, dst, nm);
A('simulink/Ports & Subsystems/Model', 'Shaddad_Plant', 'ModelName', 'Shaddad_Plant', 'SimulationMode', 'Normal');
src = {'scen', 'mcu.out1k', 'mcu.out10', 'can1.mcu_fast_rx', 'can1.mcu_slow_rx', 'bms.cmd_d'};
for k = 1:numel(R.in)
    sp = ['Spec_Plant_' R.in(k).name];
    local_spec(s, sp, R.in(k).type, R.in(k).ts);
    local_pick(s, src{k}, [sp '/1']);
    L([sp '/1'], sprintf('Shaddad_Plant/%d', k), R.in(k).name);
end
% T16 loop breaker (rule 8 / D36): a referenced model's output function is monolithic, so Plant.elec_hw
% (internally delayed by Electronics_Plant/DI_Latency) still closes artificial 1 ms loops with
% MCU.out1k -> Plant.in2 and with CAN1_Net (mcu_reset frame gating) -> Plant.in4. The MCU samples its
% GPIO / reset inputs at the start of Task_1k (one tick after the pins settle); CAN1/CAN2 gating sees the
% same sampled word, so it is published once, as plant.elec_hw_d. 'Minimize algebraic loop occurrences' is
% not applicable (Shaddad_BMS has direct feedthrough), so the breaker is explicit.
% IC = DI word at key-on (E-stop loops closed, key on, lid closed, implement plug; relay open): an
% all-zero word reads as 'E-stop pressed' and would latch HW_ESTOP in the first Task_10 step.
A('simulink/Discrete/Unit Delay', 'ElecHw_Delay', 'InitialCondition', 'scn_ic_elec_hw(P, VC_IMPL)', ...
    'SampleTime', 'Ts.base');
L(sprintf('Shaddad_Plant/%d', jhw), 'ElecHw_Delay/1', 'elec_hw');
L('ElecHw_Delay/1', 'plant_elec_hw_d/1', 'elec_hw_d');
for k = [1:jhw - 1, jhw + 1:numel(R.out)]
    L(sprintf('Shaddad_Plant/%d', k), ['plant_' R.out(k).name '/1'], R.out(k).name);
end
set_param(s, 'Description', ['Plant (ICD 3.1): Model Shaddad_Plant; the DI word leaves through ElecHw_Delay ' ...
    '(sampled by the MCU, rule 8, D36) as plant.elec_hw_d.']);
end

function local_gnc(s, Rc)
% MissionCmd_RT and Signal Specifications -> GNC_Variant (in 1 mcu_imu, 2 mcu_odom, 3 mcu_status, 4 mcu_power,
% 5 gnss_raw, 6 lidar_scan, 7 lidar_cloud, 8 spray, 9 mcmd; out 1 comp_cmd, 2 nav_state, 3 perception,
% 4 gnc_status, 5 gnc_debug, 6 nav_diag)
local_component(s, 'gnc', {Rc.out.name});
A = @(lib, name, varargin) shaddad_bu('add', lib, [s '/' name], varargin{:});
L = @(src, dst, nm) shaddad_bu('line', s, src, dst, nm);
local_gnc_variant([s '/GNC_Variant'], Rc);
A('simulink/Signal Attributes/Rate Transition', 'MissionCmd_RT', 'Integrity', 'on', 'Deterministic', 'on', ...
    'OutPortSampleTimeOpt', 'Specify', 'OutPortSampleTime', 'Ts.mcmd', 'InitialCondition', 'P.ic.Bus_MissionCmd');
local_pick(s, 'scen.mcmd', 'MissionCmd_RT/1');
