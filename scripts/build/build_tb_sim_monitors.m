function build_tb_sim_monitors()
%BUILD_TB_SIM_MONITORS  Generate tests/integration/tb_sim_monitors.slx, the Sim_Monitors unit bench (T-INT-12).
%
%   Root Inports with the Sim_Monitors port buses and rates (driven by external-input Datasets from
%   tests/integration/mon_tb_input.m) -> Subsystem Reference Sim_Monitors -> root Outport kpi.
%   Configuration: ConfigSetRef Shaddad_Ref (cs_Shaddad). Idempotent (build plan rule 3).
%   Layout: the file saves through shaddad_bu('save') (layout spec 7), every signal line named (L5).

mdl = 'tb_sim_monitors';
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
file = fullfile(root, 'tests', 'integration', [mdl '.slx']);
T = build_stubs('table');
R = T(strcmp({T.name}, 'Sim_Monitors'));
shaddad_bu('fresh', mdl, file, 'model');
shaddad_configsets('attach', mdl);
set_param(mdl, 'Description', 'Sim_Monitors unit bench (T-INT-12). Generated by scripts/build/build_tb_sim_monitors.m.');
for k = 1:numel(R.in)
    add_block('simulink/Sources/In1', [mdl '/' R.in(k).name], 'Port', num2str(k), ...
        'OutDataTypeStr', R.in(k).type, 'SampleTime', shaddad_bu('tsexpr', R.in(k).ts), 'BusOutputAsStruct', 'on');
end
add_block('simulink/Ports & Subsystems/Subsystem Reference', [mdl '/Monitors'], 'ReferencedSubsystem', 'Sim_Monitors');
for k = 1:numel(R.in)
    shaddad_bu('nline', mdl, [R.in(k).name '/1'], sprintf('Monitors/%d', k), R.in(k).name);
end
add_block('simulink/Sinks/Out1', [mdl '/kpi'], 'OutDataTypeStr', 'Bus: Bus_SimKPI');
shaddad_bu('nline', mdl, 'Monitors/1', 'kpi/1', 'kpi');
shaddad_bu('save', mdl, file);
end
